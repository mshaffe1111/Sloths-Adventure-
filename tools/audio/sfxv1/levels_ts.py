"""Write src/audio/sfxRecLevels.ts from levels.json (calib.py's take gains, previews.py's bed gains), with the in-play trims on top
(polish-sfx, 2026-10-30).

    python3 tools/audio/sfxv1/levels_ts.py [levels.json] [src/audio/sfxRecLevels.ts]

Run it only while no dev server is rendering (the game file changing reloads its page).
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'levels.json')
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, '..', '..', '..', 'src', 'audio', 'sfxRecLevels.ts')
L = json.load(open(src))
# Pokey's steps are levelled to the footstep page Matt picked from, not by calib.py (feet-levels.json)
FEET = json.load(open(os.path.join(HERE, 'feet-levels.json')))
L.update({k: v for k, v in FEET.items() if not k.startswith('_')})
# measured in real play (capture.cjs), not in calib's one-effect renders
TRIM = {'rock': -3.0}

HEAD = """/**
 * Each recorded take's gain (dB), from tools/audio/sfxv1/calib.py: every take is set to where the loudness plan (SN-2) put the old
 * effect it replaces, measured through the game's own master chain. BED_DB is each world bed's gain (previews.py, matched to the old
 * ambience's loudness). Generated by tools/audio/sfxv1/levels_ts.py: re-run calib.py, then it, after changing a take. The rock is 3 dB
 * under calib's level: in real play (tools/audio/sfxv1/capture.cjs, 4-4) its moments stood 3.5 dB over the music's loudest, and Matt
 * called the rocks annoying.
 */
"""
lines = [HEAD.rstrip('\n'), 'export const TAKE_DB: Readonly<Record<string, readonly number[]>> = {']
for fx in sorted(k for k in L if k != 'beds'):
    t = TRIM.get(fx, 0.0)
    lines.append(f"  {fx}: [{', '.join(str(round(v + t, 2)) for v in L[fx])}],")
lines.append('};')
beds = L.get('beds', {})
lines.append('export const BED_DB: Readonly<Record<number, number>> = { '
             + ', '.join(f'{w}: {beds[w]}' for w in sorted(beds, key=int)) + ' };')
open(dst, 'w').write('\n'.join(lines) + '\n')
print('wrote', dst, len(L) - ('beds' in L), 'effects,', len(beds), 'beds')
