// R-165.124: fly the landing judge's plain flights on the real engine (src/game/gen2/landFlights.ts flyLandFlights) and write them to
// src/game/gen2/landFlights.data.ts. Re-run when the engine's movement changes; landFlights.test.ts fails until the table matches.
//   npx tsx tools/engine/landflights.ts
import fs from 'node:fs';
import { flyLandFlights } from '../../src/game/gen2/landFlights.ts';

async function main() {
  const t: Record<string, unknown> = {};
  for (const s of ['normal', 'easy'] as const) t[s] = await flyLandFlights(s, '1-1');
  const file = new URL('../../src/game/gen2/landFlights.data.ts', import.meta.url);
  fs.writeFileSync(file, `// Generated by tools/engine/landflights.ts (flown on the real engine): do not edit by hand. landFlights.test.ts proves it.
import type { FlightTable } from './landFlights.ts';
export const LAND_FLIGHTS: FlightTable = ${JSON.stringify(t)};
`);
  console.log('landflights: wrote', file.pathname);
}
void main();
