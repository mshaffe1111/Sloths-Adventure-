// Where tools/engine/seedlist.ts writes a stage's proven list (R-165.112): the list itself to src/game/gen2/proven/seeds-<stage>.ts (its
// own lazy chunk in the build, never in the game's main script) and the stage's line in src/game/gen2/provenIndex.ts (count, version and
// loader: all the main script holds, the same size whatever the list's length).
import fs from 'node:fs';
import { listVersion, type PackedList } from '../../src/game/gen2/seedList.ts';
import { PROVEN_INDEX } from '../../src/game/gen2/provenIndex.ts';

const DIR = 'src/game/gen2';
export const listFile = (id: string): string => `${DIR}/proven/seeds-${id}.ts`;

/** write `list` as the stage's list file and re-write the index with its line; returns the list file's bytes */
export function writeSeedList(id: string, list: PackedList): number {
  if (!/^[\w-]+$/.test(id)) throw new Error(`seedlist: "${id}" is not a stage id a file can be named for`);
  const text = `// Generated by tools/engine/seedlist.ts: do not edit by hand. ${id}'s proven seeds (gen2/seedList.ts), each clean on both settings, with
// its proven plan packed (seedList.ts packPlan: Play replays it); quiet: each seed's longest quiet stretch on Normal (s, the goal run-out
// excluded); outro: the goal section's px. Loaded on its own (seedList.ts loadSeedList): never import this file by name from the game.
import type { PackedList } from '../seedList.ts';
export const LIST: PackedList = ${JSON.stringify(list)};
`;
  fs.mkdirSync(`${DIR}/proven`, { recursive: true });
  fs.writeFileSync(listFile(id), text);
  const lines: Record<string, { n: number; version: string }> = {};
  for (const [k, e] of Object.entries(PROVEN_INDEX)) lines[k] = { n: e.n, version: e.version };
  lines[id] = { n: list.seeds.length, version: listVersion(list) };
  const index = `// Generated by tools/engine/seedlist.ts: do not edit by hand. Every stage that has a proven seed list (gen2/seedList.ts): how many seeds
// it holds, the list's version (seedList.ts listVersion) and how to load it. This is ALL the game's main script holds of a list: each
// list is its own file under proven/, loaded on its own (R-165.112), so this file's size does not grow with a list.
import type { PackedList } from './seedList.ts';
export const PROVEN_INDEX: Record<string, { n: number; version: string; load: () => Promise<{ LIST: PackedList }> }> = {
${Object.keys(lines).sort().map((k) => `  '${k}': { n: ${lines[k].n}, version: '${lines[k].version}', load: () => import('./proven/seeds-${k}.ts') },`).join('\n')}
};
`;
  fs.writeFileSync(`${DIR}/provenIndex.ts`, index);
  return Buffer.byteLength(text);
}
