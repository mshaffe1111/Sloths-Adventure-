import '../src/game/headlessDom.ts';
import { generateAllLevels } from '../src/game/worldsData.ts';
import { buildGen2Stage } from '../src/game/gen2/pipeline.ts';
import { w1World } from '../src/game/gen2/worlds/w1.ts';
const cfg = generateAllLevels().find((l) => l.id === '1-1')!;
const [seed, diff, x0, x1] = [Number(process.argv[2]), process.argv[3] as 'normal' | 'easy', Number(process.argv[4]), Number(process.argv[5])];
const st = buildGen2Stage({ config: cfg, kit: w1World(), seed, difficulty: diff });
for (const p of st.platforms.filter((p) => p.x < x1 && p.x + p.width > x0).sort((a, b) => a.x - b.x)) console.log(p.id, p.type, p.style, 'x', p.x, '..', p.x + p.width, 'y', p.y, 'h', p.height, (p as any).catch ? 'CATCH' : '');
console.log('heartFalls', JSON.stringify((st as any).heartFalls?.filter((h: any) => h.x1 > x0 && h.x0 < x1)));
console.log('drops', JSON.stringify(st.gen2.drops?.filter((h: any) => h.x1 > x0 && h.x0 < x1)));
console.log('sections', JSON.stringify(st.gen2.sections.filter((q) => q.x1 > x0 && q.x0 < x1).map((q) => [q.template, q.x0, q.x1, q.mirrored])));
