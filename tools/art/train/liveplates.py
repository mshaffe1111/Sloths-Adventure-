"""Moving parts of the story plates, from Wan clips of the plates (cinemagraphs).

  python3 liveplates.py council nest-storm ...  -> sloths-fixes/src/assets/story/live/<plate>.webp and src/game/livePlateData.ts

Only where the clip moves (fire, fireflies, rain, mist) is kept: everywhere else is clear, so the sharp painting shows through and the sheet stays
small. Each sheet is a grid of the clip's frames, at SCALE of the clip's size; the data says where the clip sits on the plate's own picture.
"""
import json, re, sys
from pathlib import Path
import numpy as np
from PIL import Image
from scipy import ndimage

S = Path((str(__import__('pathlib').Path(__file__).resolve().parents[1]) + '/train/vids'))
GAME = __import__('pathlib').Path(str(__import__('pathlib').Path(__file__).resolve().parents[3]))
OUT = GAME / 'src/assets/story/live'
DATA = GAME / 'src/game/livePlateData.ts'
SCALE = 0.75
COLS = 5
# every other frame (the game blends between neighbours, so 8 a second still looks smooth)
STEP = 2
# the clip was made from the plate resized to 860 x 480 and cropped 14 px each side (launch_vids / cut inputs)
PW, PH = 1024, 572


def build(plate: str):
    fs = sorted((S / f'cut-{plate}').glob('*.png'))[::STEP]
    A = np.stack([np.asarray(Image.open(f).convert('RGB')) for f in fs]).astype(np.float32)
    n, h, w, _ = A.shape
    lum = A.mean(axis=3)
    move = lum.std(axis=0)
    mask = move > 3.0
    mask = ndimage.binary_opening(mask, iterations=1)
    mask = ndimage.binary_dilation(mask, iterations=6)
    soft = ndimage.gaussian_filter(mask.astype(np.float32), 4)
    alpha = (np.clip(soft * 1.6, 0, 1) * 255).astype(np.uint8)
    cover = (alpha > 8).mean()
    fw, fh = int(w * SCALE), int(h * SCALE)
    rows = (n + COLS - 1) // COLS
    sheet = Image.new('RGBA', (fw * COLS, fh * rows), (0, 0, 0, 0))
    for i in range(n):
        im = Image.fromarray(np.dstack([A[i].astype(np.uint8), alpha]), 'RGBA').resize((fw, fh), Image.LANCZOS)
        sheet.paste(im, ((i % COLS) * fw, (i // COLS) * fh))
    OUT.mkdir(parents=True, exist_ok=True)
    sheet.save(OUT / f'{plate}.webp', 'WEBP', quality=78, method=6)
    k = PW / 860
    meta = dict(n=n, cols=COLS, w=fw, h=fh, fps=16 // STEP, x=round(14 * k, 2), y=0, pw=round(w * k, 2), ph=PH)
    print(plate, meta, f'moving {cover:.0%}', (OUT / f'{plate}.webp').stat().st_size // 1024, 'KB')
    return meta


def write(d: dict):
    old = {}
    if DATA.exists():
        m = re.search(r'LIVE_PLATES: Record<string, LivePlate> = (\{.*?\});', DATA.read_text(), re.S)
        if m:
            old = json.loads(m.group(1))
    old.update(d)
    DATA.write_text(f'''/** Generated by the live-plate cutter (Wan clips of the story plates, only the parts that move). Do not edit by hand. */
export interface LivePlate {{
  n: number; cols: number; w: number; h: number; fps: number;
  /** where the clip sits on the plate's own picture, in its pixels */
  x: number; y: number; pw: number; ph: number;
}}
export const LIVE_PLATES: Record<string, LivePlate> = {json.dumps(old, indent=1)};
''')


if __name__ == '__main__':
    write({p: build(p) for p in sys.argv[1:]})
