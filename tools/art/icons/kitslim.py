"""icons-painted: the old 10-30 kit's 22 icon pieces are replaced by the painted icons (src/assets/icons), so ui-kit.webp keeps only
the pieces still drawn (lockBadge, starFull, starEmpty). python3 -I tools/art/icons/kitslim.py   (rewrites the sheet and uiKitData.ts)"""
import re, json
from pathlib import Path
from PIL import Image
R = Path(__file__).resolve().parents[3]
data = (R / 'src/game/uiKitData.ts').read_text()
frames = json.loads(re.search(r'UI_KIT: Record<string, UiFrame> = (\{.*\});', data).group(1))
keep = ['lockBadge', 'starFull', 'starEmpty']
sheet = Image.open(R / 'src/assets/ui/ui-kit.webp').convert('RGBA')
pieces = [(k, sheet.crop((frames[k]['x'], frames[k]['y'], frames[k]['x'] + frames[k]['w'], frames[k]['y'] + frames[k]['h']))) for k in keep]
W = sum(p.width for _, p in pieces) + 4 * (len(pieces) - 1); H = max(p.height for _, p in pieces)
out = Image.new('RGBA', (W, H), (0, 0, 0, 0)); x = 0; nf = {}
for k, p in pieces:
    out.paste(p, (x, 0)); nf[k] = {'x': x, 'y': 0, 'w': p.width, 'h': p.height}; x += p.width + 4
out.save(R / 'src/assets/ui/ui-kit.webp', 'WEBP', quality=90, method=6)
(R / 'src/game/uiKitData.ts').write_text(
    "// generated by tools/art/hfui/uicut.py and uifix.py (2026-10-30), slimmed by tools/art/icons/kitslim.py (2026-11-01): the lock badge\n"
    "// and the star slots of the painted menu kit (its 22 icons were replaced by the painted icons in src/assets/icons)\n"
    "export interface UiFrame { x: number; y: number; w: number; h: number }\n"
    f"export const UI_KIT_SIZE = {{ w: {W}, h: {H} }};\n"
    f"export const UI_KIT: Record<string, UiFrame> = {json.dumps(nf, separators=(',', ':'))};\n")
print(W, H, (R / 'src/assets/ui/ui-kit.webp').stat().st_size)
