"""ART 11-13 (R-165.178): pack Pokey's two-hand climb into src/assets/hero/hero-climb2.webp + hero-climb2.json (packed like hero-rope:
one row, in the order first used). Engine code is not touched: the engine member reads the JSON (B14 / the lattice wiring).

    python3 -I tools/art/hf1113/climbpack.py tools/art/hf1113/climbpicks.json

climbpicks.json: {"source", "cycle": [frame...], "still": frame, "dir": cut dir holding <frame>.png + grips.json (climbcut.py output)}.
Scale: the start had him STAND_START px tall standing (climbstarts.py: 200 sheet px x 2.8); frames are packed at STAND_PX per standing
height, so 1 game unit = STAND_PX / 89.1 sheet px (heroSprite.ts:30, D41). Each frame carries its two grips (where each paw closes on its
vine, sheet px from the frame's top left) and gap (the vines' spacing in sheet px: 80 game units in the vine field).
"""
import json, sys
from pathlib import Path
from PIL import Image

GAME = Path(__file__).resolve().parents[3]
STAND_START = 200 * 2.8
STAND_PX = 300
GAP = 2


def main(pp):
    picks = json.loads(Path(pp).read_text())
    d = GAME / picks['dir']
    grips = json.loads((d / 'grips.json').read_text())
    order = []
    for n in picks['cycle'] + [picks['still']]:
        if n not in order:
            order.append(n)
    k = STAND_PX / STAND_START
    ims, fr, x = [], {}, 0
    for n in order:
        im = Image.open(d / f'{n}.png').convert('RGBA')
        im = im.resize((round(im.width * k), round(im.height * k)), Image.LANCZOS)
        g = grips[n]
        gs = [[round(q['x'] * k, 1), round(q['y'] * k, 1)] for q in g['grips']]
        vx = g['vines_x']
        fr[n] = {'x': x, 'y': 0, 'w': im.width, 'h': im.height, 'grips': gs,
                 'gap': round((vx[1] - vx[0]) * k, 1) if len(vx) == 2 else None,
                 'ax': round(((gs[0][0] + gs[1][0]) / 2) if len(gs) == 2 else im.width / 2, 1)}
        ims.append((x, im)); x += im.width + GAP
    sheet = Image.new('RGBA', (x - GAP, max(im.height for _, im in ims)), (0, 0, 0, 0))
    for xx, im in ims:
        sheet.alpha_composite(im, (xx, 0))
    out = GAME / 'src/assets/hero/hero-climb2.webp'
    sheet.save(out, 'WEBP', quality=92, method=6)
    meta = {'note': 'generated by tools/art/hf1113/climbpack.py; never hand-edit', 'source': picks['source'],
            'stand_px': STAND_PX, 'pokey_units': 89.1, 'vine_gap_units': 80,
            'grips': 'per frame [[x, y] left paw, [x, y] right paw]: where each paw closes on its vine, sheet px from the frame top left',
            'ax': 'x midway between the grips (his body hangs centred between the vines)',
            'frames': fr, 'cycle': picks['cycle'], 'still': picks['still']}
    (GAME / 'src/assets/hero/hero-climb2.json').write_text(json.dumps(meta, indent=1))
    print(out, out.stat().st_size, sheet.size)


if __name__ == '__main__':
    main(sys.argv[1])
