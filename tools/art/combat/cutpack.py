"""R-159.1 art cut-in (w8-rope2, 2026-11-04): the lead-accepted Hugging Face picks for World 1's tricks, keyed off magenta
(w6to10/geminicut.py cut_cell, its despill), trimmed to one box per creature so every frame keeps the same anchor, scaled and packed into
one atlas, with its frame table:
    the vine snake (take s65-7, Matt's option (a)): hang (clip s3, a loop), tell (clip s3 frames 0-12), flinch (stiffen s3 frames 0-10),
      bite (clip s11 frames 14-24: the lunge out, its smeared frames 25-29 left out) when its frames are in;
    the rolled boa (take s60-7), one ball turned in code.
    python3 tools/art/combat/cutpack.py <vine frames dir> <ball take.webp> <out atlas.webp> <out frames.ts> <review.jpg>
(<vine frames dir>/<move>/r159-vine-<move>-sN_###.webp, unpacked from the clips' carriers with tools/art/w5/unpack_carrier.py.)
"""
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'w6to10'))
from geminicut import cut_cell  # noqa: E402

VINE, BALL, OUT, TS, REVIEW = (Path(a) for a in sys.argv[1:6])
# (move, clip seed, frames used, every n-th)
MOVES = [('hang', 3, range(0, 49), 4), ('tell', 3, range(0, 13), 2), ('flinch', 3, range(0, 11), 2), ('bite', 11, range(14, 25), 2)]
VINE_H = 220  # packed height of the vine snake's box (it is drawn about 180 world px tall: the lead's +20% sideways)
BALL_H = 96


def content(im):
    """the clip pads its start into the frame with pale-pink bands above and below: only the magenta field is the picture"""
    a = np.asarray(im.convert('RGB')).astype(int)
    rows = np.where(((a[..., 0] > 170) & (a[..., 2] > 170) & (a[..., 1] < 110)).mean(axis=1) > 0.3)[0]
    return im.crop((0, int(rows.min()) + 2, im.width, int(rows.max()) - 1))


def key(im):
    sp = cut_cell(content(im), 'magenta', {})
    # (the pad's pale-pink edge pixels left at the frame's corners: nothing of the snake is that pale)
    a = np.asarray(sp).copy()
    pale = (a[..., 0] > 205) & (a[..., 1] > 185) & (a[..., 2] > 205)
    a[..., 3][pale] = 0
    return Image.fromarray(a, 'RGBA')


frames = {}
cells = []
# one box for every vine frame, so the snake hangs from the same point in each
vine = {}
for move, seed, rng, step in MOVES:
    d = VINE / ('stiffen' if move == 'flinch' else move)
    got = []
    for i in list(rng)[::step]:
        f = d / f"r159-vine-{'stiffen' if move == 'flinch' else move}-s{seed}_{i:03d}.webp"
        if f.exists():
            got.append(key(Image.open(f)))
    if got:
        vine[move] = got
boxes = [im.getchannel('A').point(lambda v: 255 if v > 40 else 0).getbbox() for ims in vine.values() for im in ims]
bx = (min(b[0] for b in boxes), min(b[1] for b in boxes), max(b[2] for b in boxes), max(b[3] for b in boxes))
for move, ims in vine.items():
    for n, im in enumerate(ims):
        c = im.crop(bx)
        # (the clip frame's own edge leaves a faint line at the box's right side and its top and bottom: the snake never reaches them)
        a = np.asarray(c).copy()
        a[:, -3:, 3] = 0
        a[:2, :, 3] = 0
        a[-2:, :, 3] = 0
        c = Image.fromarray(a, 'RGBA')
        k = VINE_H / c.height
        cells.append((f'vine_{move}_{n:02d}', c.resize((round(c.width * k), VINE_H), Image.LANCZOS)))

ball = cut_cell(Image.open(BALL), 'magenta', {})
ball = ball.crop(ball.getchannel('A').point(lambda v: 255 if v > 40 else 0).getbbox())
k = BALL_H / ball.height
cells.append(('ball', ball.resize((round(ball.width * k), BALL_H), Image.LANCZOS)))

# pack in rows no wider than 2048
x = y = rowh = 0
W = 2048
pos = []
for name, im in cells:
    if x + im.width > W:
        x, y, rowh = 0, y + rowh + 2, 0
    pos.append((name, im, x, y))
    x += im.width + 2
    rowh = max(rowh, im.height)
H = y + rowh
sheet = Image.new('RGBA', (W, H), (0, 0, 0, 0))
for name, im, x, y in pos:
    sheet.alpha_composite(im, (x, y))
    # (the vine snake's anchor: the top of its box, at its body's straight side, the edge that lies against the liana)
    ax = 0.0 if name.startswith('vine') else im.width / 2
    ay = 0.0 if name.startswith('vine') else im.height / 2
    frames[name] = {'x': x, 'y': y, 'w': im.width, 'h': im.height, 'ax': round(ax, 1), 'ay': round(ay, 1)}
sheet.save(OUT, 'WEBP', quality=90, method=6)
counts = {m: len(v) for m, v in vine.items()}
TS.write_text('// generated by tools/art/combat/cutpack.py (R-159.1): where each of World 1\'s trick pictures sits in\n'
              '// src/assets/enemies/w1tricks.webp. The vine snake\'s frames share one box (anchor: its top-left, the straight side that lies\n'
              '// against the liana); the ball is anchored at its middle.\n'
              'export interface TrickFrame { x: number; y: number; w: number; h: number; ax: number; ay: number }\n'
              f'export const TRICK_FRAMES: Record<string, TrickFrame> = {json.dumps(frames)};\n'
              f'export const VINE_MOVES: Record<string, number> = {json.dumps(counts)};\n')
# review: every frame on dark and on light
rv = Image.new('RGB', (W, H * 2 + 8), (30, 30, 30))
light = Image.new('RGBA', (W, H), (200, 210, 190, 255))
light.alpha_composite(sheet)
dark = Image.new('RGBA', (W, H), (34, 40, 30, 255))
dark.alpha_composite(sheet)
rv.paste(dark.convert('RGB'), (0, 0))
rv.paste(light.convert('RGB'), (0, H + 8))
rv.save(REVIEW, quality=85)
print(OUT, sheet.size, counts, 'ball', frames['ball']['w'], 'x', frames['ball']['h'])
