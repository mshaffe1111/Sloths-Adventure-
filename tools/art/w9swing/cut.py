"""Cut World 9's irons (2026-10-29) from the Hugging Face takes (make_spec.py; the takes unpacked from the job's carrier with
tools/art/w5/unpack_carrier.py): each pick keyed off the magenta with the repo's cut (w6to10/geminicut.py cut_cell) and a second
despill on the rim, graded from the takes' lilac toward the kit's warm charcoal, cropped to its piece; a chain strand is cut to a whole
number of links (its alpha's row profile repeats every link pair: the period found by autocorrelation), so laid end to end it never
shows a seam. Packed into src/assets/w9/irons.webp with src/game/w9IronsData.ts, and a review sheet (every take, the picks on dark and
mid-grey, a chain tiled) at reference/prop-sheets/qa-notes/w9-swing/irons-review.jpg.
    python3 -I tools/art/w9swing/cut.py <takes dir>
"""
import json, sys
from pathlib import Path
import numpy as np
from PIL import Image, ImageDraw
from scipy import ndimage
ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / 'tools/art/w6to10'))
from geminicut import cut_cell  # noqa: E402

TAKES = Path(sys.argv[1])
# piece: (take, box in the 1024 take, anchor kind)
PICKS = {
    'chainA': ('w9chains-s55-29', (380, 20, 480, 1024), 'strand'),
    'chainB': ('w9chains-s70-11', (380, 20, 480, 1024), 'strand'),
    'chainC': ('w9chains-s55-29', (60, 20, 160, 1024), 'strand'),
    'bucket': ('w9chains-s70-11', (580, 30, 870, 470), 'foot'),
    'pulley': ('w9chains-s70-11', (600, 490, 840, 820), 'wheel'),
    'eyebolt': ('w9chains-s70-11', (830, 790, 975, 950), 'ring'),
}


def keyed(name, box):
    sp = cut_cell(Image.open(TAKES / f'{name}.webp').convert('RGB').crop(box), 'magenta', {})
    a = np.asarray(sp).astype(np.float32)
    band = ndimage.binary_dilation(a[..., 3] < 128, iterations=4) & (a[..., 3] > 0)
    ex = np.clip(np.minimum(a[..., 0], a[..., 2]) - a[..., 1] - 4, 0, None) * band
    a[..., 0] -= ex; a[..., 2] -= ex
    # (the takes' iron is lilac, rgb about 70/62/82: pulled to the kit's warm charcoal, about 74/68/66, a touch lighter so it reads
    # against the dark smoke)
    a[..., 0] *= 1.10; a[..., 1] *= 1.10; a[..., 2] *= 0.86
    return np.clip(a, 0, 255)


pieces = {}
for n, (take, box, kind) in PICKS.items():
    a = keyed(take, box)
    if kind == 'strand':
        prof = (a[..., 3] > 128).sum(axis=1).astype(np.float32)
        p0 = prof - prof.mean()
        ac = np.correlate(p0, p0, 'full')[len(p0) - 1:]
        lo = 90
        period = lo + int(np.argmax(ac[lo:400]))
        # (start where the profile is narrowest, the middle of a bar between rings, so the cut falls on a bar; keep whole periods)
        y0 = int(np.argmin(prof[20:20 + period])) + 20
        k = max(1, (len(prof) - y0 - 4) // period)
        a = a[y0:y0 + k * period]
        print(n, 'period', period, 'links', k, 'h', a.shape[0])
    pieces[n] = (Image.fromarray(a.astype(np.uint8), 'RGBA'), kind)

# pack in a row
pad = 4
W = sum(im.width + pad for im, _ in pieces.values())
H = max(im.height for im, _ in pieces.values())
sheet = Image.new('RGBA', (W, H), (0, 0, 0, 0))
frames = {}
x = 0
for n, (im, kind) in pieces.items():
    sheet.paste(im, (x, 0))
    w, h = im.size
    ax, ay = w / 2, {'strand': 0, 'foot': h, 'wheel': h * 0.58, 'ring': h * 0.70}[kind]
    frames[n] = {'x': x, 'y': 0, 'w': w, 'h': h, 'ax': round(ax, 1), 'ay': round(ay, 1)}
    x += w + pad
out = ROOT / 'src/assets/w9/irons.webp'
out.parent.mkdir(parents=True, exist_ok=True)
sheet.save(out, 'WEBP', quality=90, method=6, exact=True)
print(out, sheet.size, out.stat().st_size)
ts = ROOT / 'src/game/w9IronsData.ts'
ts.write_text(
    '// generated by tools/art/w9swing/cut.py (2026-10-29): World 9\'s irons (Hugging Face, img2img from tools/art/w9swing/chainstart.py):\n'
    '// three chain strands (each a whole number of links, anchored at the middle of its top), the ore bucket (the middle of its foot),\n'
    '// the pulley (its wheel\'s middle) and the eye bolt (its ring\'s middle), in src/assets/w9/irons.webp\n'
    'export interface W9IronFrame { x: number; y: number; w: number; h: number; ax: number; ay: number }\n'
    "export const W9_IRONS_URL = new URL('../assets/w9/irons.webp', import.meta.url).href;\n"
    f'export const W9_IRONS = {json.dumps(frames, indent=2)} as const satisfies Record<string, W9IronFrame>;\n')
print(ts)

# review: every take, the picks on dark and on mid-grey, a chain tiled 3x
rv = ROOT / 'reference/prop-sheets/qa-notes/w9-swing/irons-review.jpg'
rv.parent.mkdir(parents=True, exist_ok=True)
takes = sorted(TAKES.glob('w9chains-*.webp'))
tw = 360
R = Image.new('RGB', (tw * len(takes), tw + 22 + 2 * (H + 40) + 20), (24, 24, 24))
d = ImageDraw.Draw(R)
for i, f in enumerate(takes):
    R.paste(Image.open(f).convert('RGB').resize((tw, tw)), (i * tw, 22))
    d.text((i * tw + 4, 4), f.stem, fill=(255, 230, 0))
y = tw + 30
for label, col in (('picks on dark (#141018)', (20, 16, 24)), ('picks on mid-grey (#808080)', (128, 128, 128))):
    bg = Image.new('RGBA', (sheet.width, H), col + (255,))
    bg.alpha_composite(sheet)
    R.paste(bg.convert('RGB').resize((min(R.width, sheet.width), H)), (0, y + 16))
    d.text((4, y), label, fill=(255, 230, 0))
    y += H + 40
R.save(rv, quality=88)
print(rv)
