"""Write src/game/w10PropsData.ts: World 10's painted set dressing, two looks of each piece (Matt's Gemini sheet w10c-set-dressing and the
HF img2img sheet w10alt), and the World 10 kit pieces it hangs (chains, hooks). Frames anchored at the middle of the foot (ax, ay).
Run from the repo root: python3 tools/art/w10/propsData.py"""
import json, os
sheets = [('W10C', 'src/assets/w6to10/gemini/w10c-set-dressing.json', '../assets/w6to10/gemini/w10c-set-dressing.webp', ''),
          ('W10ALT', 'src/assets/w6to10/props-made/w10alt.json', '../assets/w6to10/props-made/w10alt.webp', '')]
out = ['/** Generated by tools/art/w10/propsData.py: World 10\'s set dressing, two looks of each piece (w10c: Matt\'s Gemini sheet; w10alt: the HF',
       ' * img2img sheet, names ending -b). Frames anchored at the middle of the foot (ax, ay), at the painted size. Do not edit by hand. */',
       'export interface W10Frame { x: number; y: number; w: number; h: number; ax: number; ay: number }']
for name, js, url, _ in sheets:
    j = json.load(open(js))
    fr = {k: {kk: (round(v, 1) if isinstance(v, float) else v) for kk, v in f.items() if kk in ('x', 'y', 'w', 'h', 'ax', 'ay')} for k, f in j['frames'].items()}
    out.append(f"export const {name}_URL = new URL('{url}', import.meta.url).href;")
    out.append(f"export const {name}_FRAMES: Record<string, W10Frame> = " + json.dumps(fr, separators=(',', ':')) + ';')
open('src/game/w10PropsData.ts', 'w').write('\n'.join(out) + '\n')
print('ok')
