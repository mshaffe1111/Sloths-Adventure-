"""Write src/game/soldierFightData.ts from the soldiers' fight clips, src/assets/w6to10/creatures/soldier.json (attack, hurt, down for
both variants; their march and idle are Meeca's stage's, soldierAnimData.ts). Frames face RIGHT, anchored at the middle of the feet
(ax, ay). Run from the repo root: python3 tools/art/w10/soldierData.py"""
import json, os
root = os.getcwd()
parts = [('src/assets/w6to10/creatures/soldier.json', '../assets/w6to10/creatures/')]
frames, seq, urls = {}, {}, []
for path, rel in parts:
    if not os.path.exists(os.path.join(root, path)):
        continue
    j = json.load(open(os.path.join(root, path)))
    off = len(urls)
    urls += [rel + s for s in j['sheets']]
    for n, f in j['frames'].items():
        frames[n] = {**f, 's': f['s'] + off}
    seq.update(j['seq'])
out = ['/** Generated by tools/art/w10/soldierData.py from the soldiers\' fight clips (w6to10/creatures/soldier.json: attack, hurt, down, variants',
       ' * a and b). Frames face right, anchored at the middle of the feet (ax, ay), "s" the sheet. Do not edit by hand. */',
       'export interface FightFrame { s: number; x: number; y: number; w: number; h: number; ax: number; ay: number }',
       'export const FIGHT_URLS: readonly string[] = [' + ', '.join(f"new URL('{u}', import.meta.url).href" for u in urls) + '];',
       'export const FIGHT_FRAMES: Record<string, FightFrame> = ' + json.dumps({k: {kk: round(v, 1) if isinstance(v, float) else v for kk, v in f.items()} for k, f in frames.items()}, separators=(',', ':')) + ';',
       'export const FIGHT_SEQ: Record<string, string[]> = ' + json.dumps(seq, separators=(',', ':')) + ';', '']
open(os.path.join(root, 'src/game/soldierFightData.ts'), 'w').write('\n'.join(out))
print(len(frames), 'frames', sorted(seq))
