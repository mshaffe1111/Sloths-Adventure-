"""Pack the cut World 4 pieces (cut.py --names) into one atlas at half size, and write the frame table.

    python3 -I tools/art/w4/pack.py

Writes src/assets/props/w4-props.webp and src/game/w4PropsData.ts. Shelf packing, widest-first rows sorted by height."""
import json
from pathlib import Path
from PIL import Image

H = Path(__file__).resolve().parent
ROOT = H.parents[2]
NAMES = json.loads((H / 'names.json').read_text())
SCALE = 0.5
W = 2048
PAD = 4

pieces = []
for sheet, names in NAMES.items():
    for n in names:
        im = Image.open(H / 'cut' / f'{n}.png').convert('RGBA')
        im = im.resize((max(1, round(im.width * SCALE)), max(1, round(im.height * SCALE))), Image.LANCZOS)
        pieces.append((n, im))
pieces.sort(key=lambda t: -t[1].height)
frames = {}
x = y = row = 0
for n, im in pieces:
    if x + im.width > W:
        x, y, row = 0, y + row + PAD, 0
    frames[n] = (x, y, im.width, im.height)
    x += im.width + PAD
    row = max(row, im.height)
atlas = Image.new('RGBA', (W, y + row), (0, 0, 0, 0))
for n, im in pieces:
    fx, fy, _, _ = frames[n]
    atlas.paste(im, (fx, fy))
out = ROOT / 'src/assets/props/w4-props.webp'
atlas.save(out, 'WEBP', quality=86, method=6)
print('atlas', atlas.size, out.stat().st_size, 'bytes')
lines = [
    '// generated by tools/art/w4/pack.py from World 4 art batch 1 (Hugging Face, 2026-10-25): where each piece sits in w4-props.webp',
    'export interface W4Frame { x: number; y: number; w: number; h: number }',
    'export const W4_FRAMES = {',
]
for n in sorted(frames):
    fx, fy, fw, fh = frames[n]
    lines.append(f'  {n}: {{ x: {fx}, y: {fy}, w: {fw}, h: {fh} }},')
lines.append('} satisfies Record<string, W4Frame>;')
(ROOT / 'src/game/w4PropsData.ts').write_text('\n'.join(lines) + '\n')
