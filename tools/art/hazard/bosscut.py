"""Cut the bosses' painted attacks (2026-10-29, hazard-anim round 3) from the Hugging Face takes (spec-hfb-bossatk.json, starts
bossstarts.py): each picked cell keyed off the magenta with the repo's cut and despill (w6to10/geminicut.py cut_cell), a second despill
over the whole piece (r and b both over g is the key's tint), every piece of the cell kept (a geyser's spray, a puddle's splashes),
trimmed and scaled (the tall columns to 360 px high, the strips to 900 px wide, the rest to 160 px), packed into
src/assets/bosses/boss-atk.webp with src/game/bossAtkData.ts; then the review sheet, every piece on dark and mid-grey.
    python3 -I tools/art/hazard/bosscut.py <takes dir> <game checkout> <review.jpg>
"""
import json, sys
from pathlib import Path
import numpy as np
from PIL import Image, ImageDraw
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'w6to10'))
from geminicut import cut_cell  # noqa: E402

TAKES, GAME, REVIEW = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
COLS = ['colLava', 'colThorn', 'colRock', 'colCrystal', 'colWeb', 'colTail']
# (name, take, cell, kind): cols are 6 cells across a 1536 x 768 take; bits a 4 x 4 grid of 256; strips nine rows of 128 across 1536
PICKS = [(n, 'bosscols-s82-7', i, 'col') for i, n in enumerate(COLS)]
PICKS += [('spikeStone', 'bossbits-s82-7', 0, 'bit'), ('bat', 'bossbits-s82-7', 1, 'bit'), ('club', 'bossbits-s82-7', 3, 'bit'),
          ('globLava', 'bossbits-s82-7', 4, 'bit'), ('globMud', 'bossbits-s82-7', 5, 'bit'), ('puddleLava', 'bossbits-s82-7', 6, 'bit'),
          ('spikeIce', 'bossbits-s82-7', 8, 'bit'), ('club2', 'bossbits-s82-7', 10, 'bit'), ('globVenom', 'bossbits-s82-7', 12, 'bit'),
          ('puddleVenom', 'bossbits-s82-7', 13, 'bit'), ('embers', 'bossbits-s82-7', 14, 'bit'), ('rock', 'bossbits-s82-7', 15, 'bit'),
          ('dart', 'bossbits-s70-7', 3, 'bit'), ('dart2', 'bossbits-s70-7', 11, 'bit'), ('puddleMud', 'bossbits-s70-7', 7, 'bit')]
# the strips: the brighter s82-23 takes, but the spear from s70-7 (s82-23's grew a crossguard halfway along)
STRIPS = json.loads(sys.argv[4]) if len(sys.argv) > 4 else {
    'jetFire': ['bossstrips-s82-23', 0], 'whipVine': ['bossstrips-s82-23', 1], 'beamMagic': ['bossstrips-s82-23', 2],
    'jabSpear': ['bossstrips-s70-7', 3], 'groundFire': ['bossstrips-s82-23', 7], 'lavaStrip': ['bossstrips-s82-23', 8]}
PICKS += [(n, take, row, 'strip') for n, (take, row) in STRIPS.items()]


def box(kind, cell, im):
    if kind == 'col':
        w = im.width // 6
        return (cell * w, 0, (cell + 1) * w, im.height)
    if kind == 'bit':
        c = im.width // 4
        return ((cell % 4) * c, (cell // 4) * c, (cell % 4 + 1) * c, (cell // 4 + 1) * c)
    h = im.height // 9
    return (0, cell * h, im.width, (cell + 1) * h)


pieces = []
for name, take, cell, kind in PICKS:
    im = Image.open(TAKES / f'{take}.webp').convert('RGB')
    sp = np.asarray(cut_cell(im.crop(box(kind, cell, im)), 'magenta', {})).astype(np.float32)
    ex = np.clip(np.minimum(sp[..., 0], sp[..., 2]) - sp[..., 1] - 6, 0, None) * (sp[..., 3] > 0)
    # (keep the bright pinks a lava or a flame paints: only where the pixel is near the key's hue, r and b close, is it spill)
    near_key = np.abs(sp[..., 0] - sp[..., 2]) < 50
    ex *= near_key
    sp[..., 0] -= ex
    sp[..., 2] -= ex
    p = Image.fromarray(np.clip(sp, 0, 255).astype(np.uint8), 'RGBA')
    p = p.crop(p.getchannel('A').getbbox())
    if kind == 'col':
        k = 360 / p.height
    elif kind == 'strip':
        k = 900 / p.width
    else:
        k = 160 / max(p.size)
    pieces.append((name, p.resize((max(1, round(p.width * k)), max(1, round(p.height * k))), Image.LANCZOS)))

W, x, y, rowh, frames = 2048, 0, 0, 0, {}
for name, p in sorted(pieces, key=lambda q: -q[1].height):
    if x + p.width > W:
        x, y, rowh = 0, y + rowh + 2, 0
    frames[name] = dict(x=x, y=y, w=p.width, h=p.height)
    x += p.width + 2
    rowh = max(rowh, p.height)
S = Image.new('RGBA', (W, y + rowh), (0, 0, 0, 0))
for name, p in pieces:
    f = frames[name]
    S.alpha_composite(p, (f['x'], f['y']))
out = GAME / 'src/assets/bosses/boss-atk.webp'
S.save(out, 'WEBP', quality=90, method=6)
(GAME / 'src/game/bossAtkData.ts').write_text(
    '// generated by tools/art/hazard/bosscut.py (2026-10-29): where each painted boss attack sits in src/assets/bosses/boss-atk.webp\n'
    '// (Hugging Face img2img of plain-shape starts, tools/art/hazard/bossstarts.py; the picks are in bosscut.py)\n'
    'export interface AtkFrame { x: number; y: number; w: number; h: number }\n'
    f'export const BOSS_ATK: Record<string, AtkFrame> = {json.dumps(frames)};\n')
print(out, S.size, out.stat().st_size, len(frames))
R = Image.new('RGB', (S.width // 2, (S.height // 2 + 10) * 2), (24, 24, 24))
for i, col in enumerate(((20, 16, 24), (128, 128, 128))):
    bg = Image.new('RGBA', S.size, col + (255,))
    bg.alpha_composite(S)
    R.paste(bg.convert('RGB').resize((S.width // 2, S.height // 2), Image.LANCZOS), (0, i * (S.height // 2 + 10)))
REVIEW.parent.mkdir(parents=True, exist_ok=True)
R.save(REVIEW, 'JPEG', quality=88)
print(REVIEW)
