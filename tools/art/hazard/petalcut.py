"""Cut the drifting petals (2026-10-29, hazard-anim) from the Hugging Face takes (spec-hfb-petals.json, start petalstart.py), keyed off
flat green: the key flooded in from each cell's border (green over both red and blue), a soft rim, green clamped toward the brighter of
red and blue on the fringe (despill), each cell's largest piece kept, trimmed and scaled to 64 px across at most, packed into
src/assets/flora/petals.webp with src/game/petalData.ts; then the review sheet, every pick on dark, mid-grey and the World 2 gold.
    python3 -I tools/art/hazard/petalcut.py <takes dir> <game checkout> <review.jpg>
"""
import json, sys
from pathlib import Path
import numpy as np
from PIL import Image, ImageDraw
from scipy import ndimage

TAKES, GAME, REVIEW = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
# (take, cell 0..15): loose petals and small blossoms only. Left out: the roses and the cherries (not petals), cells with a green stem
# or leaf (it keys away half-gone), s70-23's purple grape bunch.
PICKS = [('petals-s82-7', c) for c in (0, 2, 3, 5, 6, 7, 9, 10, 12, 13, 14)]
PICKS += [('petals-s70-7', 7), ('petals-s70-7', 9), ('petals-s70-23', 1), ('petals-s70-23', 15), ('petals-s82-23', 4), ('petals-s82-23', 15)]


def cut(cell):
    a = np.asarray(cell.convert('RGB')).astype(np.float32)
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    k = g - np.maximum(r, b)
    lab, n = ndimage.label(k > 70)
    edge = set(np.unique(np.concatenate([lab[0], lab[-1], lab[:, 0], lab[:, -1]]))) - {0}
    bg = np.isin(lab, list(edge))
    near = ndimage.binary_dilation(bg, iterations=3) & ~bg
    alpha = np.where(bg, 0, 255).astype(np.float32)
    alpha[near] = np.clip((120 - k[near]) / 80, 0, 1) * 255
    # (despill: on the fringe, and wherever green sits well over both others, green comes down to the brighter of red and blue)
    spill = near | (k > 20)
    a[..., 1] = np.where(spill, np.minimum(g, np.maximum(r, b) + 6), g)
    out = np.dstack([a, alpha]).clip(0, 255).astype(np.uint8)
    lab2, n2 = ndimage.label(alpha > 60)
    if n2 > 1:
        sizes = ndimage.sum(np.ones(lab2.shape), lab2, range(1, n2 + 1))
        keep = ndimage.binary_dilation(lab2 == int(np.argmax(sizes)) + 1, iterations=2)
        out[..., 3] = (out[..., 3] * keep).astype(np.uint8)
    im = Image.fromarray(out, 'RGBA')
    return im.crop(im.getchannel('A').getbbox())


pieces = []
for take, c in PICKS:
    im = Image.open(TAKES / f'{take}.webp').convert('RGB')
    cs = im.width // 4
    p = cut(im.crop(((c % 4) * cs, (c // 4) * cs, (c % 4 + 1) * cs, (c // 4 + 1) * cs)))
    k = min(1, 64 / max(p.size))
    pieces.append(p.resize((max(1, round(p.width * k)), max(1, round(p.height * k))), Image.LANCZOS))
W, x, y, rowh, frames = 512, 0, 0, 0, []
for p in pieces:
    if x + p.width > W:
        x, y, rowh = 0, y + rowh + 2, 0
    frames.append(dict(x=x, y=y, w=p.width, h=p.height))
    x += p.width + 2
    rowh = max(rowh, p.height)
S = Image.new('RGBA', (W, y + rowh), (0, 0, 0, 0))
for p, f in zip(pieces, frames):
    S.alpha_composite(p, (f['x'], f['y']))
out = GAME / 'src/assets/flora/petals.webp'
S.save(out, 'WEBP', quality=92, method=6)
(GAME / 'src/game/petalData.ts').write_text(
    '// generated by tools/art/hazard/petalcut.py (2026-10-29): where each painted drifting petal sits in src/assets/flora/petals.webp\n'
    '// (Hugging Face img2img of crops of the game\'s own painted flowers, spec-hfb-petals.json)\n'
    'export interface PetalFrame { x: number; y: number; w: number; h: number }\n'
    f'export const PETALS: PetalFrame[] = {json.dumps(frames)};\n')
print(out, S.size, out.stat().st_size, len(frames), 'petals')
big = Image.new('RGB', (S.width * 2, (S.height + 6) * 3 * 2), (24, 24, 24))
for i, col in enumerate(((20, 16, 24), (128, 128, 128), (196, 160, 90))):
    bg = Image.new('RGBA', S.size, col + (255,))
    bg.alpha_composite(S)
    big.paste(bg.convert('RGB').resize((S.width * 2, S.height * 2), Image.LANCZOS), (0, i * (S.height + 6) * 2))
REVIEW.parent.mkdir(parents=True, exist_ok=True)
big.save(REVIEW, 'JPEG', quality=88)
print(REVIEW)
