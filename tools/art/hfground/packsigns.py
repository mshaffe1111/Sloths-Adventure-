"""Pack the carved water signs (hf-art-ground, 2026-10-29; VI-13) into src/assets/props/water-signs.webp and src/game/waterSignData.ts.
    python3 tools/art/hfground/packsigns.py <raw dir>
Two looks (World 5's silver garden wood, the jungle's brown), each a still frame and a rattled one: the same painting with its board
(everything above the board's foot, share BOARD of the height) turned 7 degrees about the top of the post and lifted 3 px, as a board
knocked on its nail. Each frame is 168 x 232, the foot of the post at its bottom middle.
"""
import json, sys
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from keying import depurple, key  # noqa: E402

ROOT = HERE.parents[2]
raw = Path(sys.argv[1])
PICKS = {'sign-w5': 'sign2-w5-s72-19', 'sign-jungle': 'sign2-jungle-s62-7'}
BOARD = 0.56
FW, FH = 168, 232

frames, cells = {}, []
for n, pick in PICKS.items():
    # (the jungle sign has no purple of its own: any is key spill, a pink line between its planks; World 5's keeps its lilac grass)
    k = depurple(key(Image.open(raw / f'{pick}.webp'), main_only=True), lum_max=256 if n == 'sign-jungle' else 120)
    bb = k.getbbox()
    k = k.crop(bb)
    # (the post's middle: the middle of the solid in the bottom tenth)
    a = np.asarray(k)[..., 3]
    foot = np.where(a[int(k.height * 0.9):].max(0) > 128)[0]
    px = (foot.min() + foot.max()) / 2
    s = (FH - 6) / k.height
    k = k.resize((round(k.width * s), FH - 6), Image.LANCZOS)
    px *= s
    still = Image.new('RGBA', (FW, FH), (0, 0, 0, 0))
    ox = round(FW / 2 - px)
    still.alpha_composite(k, (ox, FH - k.height))
    cut = round(FH - k.height + k.height * BOARD)
    board = still.crop((0, 0, FW, cut))
    post = still.crop((0, cut, FW, FH))
    rat = Image.new('RGBA', (FW, FH), (0, 0, 0, 0))
    rat.alpha_composite(post, (0, cut))
    # (the post runs on up behind the tilted board: its own columns, from the still, for the 22 rows above the cut, inside its edges)
    pa = np.asarray(still)[cut + 12, :, 3]
    cols = np.where(pa > 128)[0]
    if len(cols):
        stub = still.crop((int(cols.min()) + 2, cut - 22, int(cols.max()) - 1, cut + 2))
        rat.alpha_composite(stub, (int(cols.min()) + 2, cut - 22))
    tilt = board.rotate(7, resample=Image.BICUBIC, center=(FW / 2, cut - 4), expand=False)
    rat.alpha_composite(tilt, (0, -3))
    cells += [(n, still), (f'{n}-rattle', rat)]

W = FW * len(cells) + 2 * (len(cells) - 1)
S = Image.new('RGBA', (W, FH), (0, 0, 0, 0))
for i, (n, im) in enumerate(cells):
    x = i * (FW + 2)
    S.alpha_composite(im, (x, 0))
    frames[n] = {'x': x, 'y': 0, 'w': FW, 'h': FH, 'ax': FW / 2, 'ay': FH}
out = ROOT / 'src/assets/props/water-signs.webp'
S.save(out, 'WEBP', quality=90, method=6)
ts = f"""/** Generated by tools/art/hfground/packsigns.py (hf-art-ground, 2026-10-29; polish report VI-13): the water's-edge warning signs, carved
 * wood painted on Hugging Face in the kit style (no black outline, darker-hue edges, light from the upper left): sign-w5 World 5's
 * garden look (silver wood, silk and an orchid), sign-jungle Worlds 6-10 (brown wood and vine); each with its -rattle frame (the board
 * knocked on its nail). ax/ay: the middle of the post's foot. */
export interface SignFrame {{ x: number; y: number; w: number; h: number; ax: number; ay: number }}
export const WATER_SIGN_URL = new URL('../assets/props/water-signs.webp', import.meta.url).href;
export const WATER_SIGN_SIZE = {{ w: {W}, h: {FH} }};
export const WATER_SIGN_FRAMES: Record<string, SignFrame> = {json.dumps(frames)};
"""
(ROOT / 'src/game/waterSignData.ts').write_text(ts)
print(out, out.stat().st_size, W, FH)
