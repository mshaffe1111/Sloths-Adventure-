"""Pack the painted bounce plants (hf-art-ground round 3, 2026-10-29: they were drawn in code, spanArt.ts drawBounce, and in 10-1 the
toadstool's pale code stalk read as a white bar standing in the water) into src/assets/props/bounce.webp and src/game/bounceAtlasData.ts.
    python3 tools/art/hfground/packbounce.py <raw dir>
Per world (picks-bounce.json, w1..w10: each world its own plant, Matt 2026-10-29): its cap (cropped to the painting, its top row the collision line; cw: the cap's widest span, cx its
middle, as shares of the frame's width) and its stalk turned upright, one repeat of a tile that runs downward with no seam.
"""
import json, sys
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from keying import depurple, key  # noqa: E402

ROOT = HERE.parents[2]
raw = Path(sys.argv[1])
PICKS = json.loads((HERE / 'picks-bounce.json').read_text())
CAP_W = 300  # the cap frame's width, px
STALK_H = 256

cells = []
frames = {}
for sp, pk in PICKS.items():
    wspan = pk.get('span', 1.1)
    cap = depurple(key(Image.open(raw / f"{pk['cap']}.webp"), main_only=True), edge_only=1)
    # (`lift`: brighter, for a dark plant on a dark stage: World 10's iron thistle on its storm, the lead's review)
    def lifted(im, k=pk.get('lift', 1.0)):
        if k == 1.0:
            return im
        a = np.asarray(im).astype(np.float32)
        a[..., :3] = 255 * (a[..., :3] / 255) ** (1 / k) * min(1.15, k)
        return Image.fromarray(np.clip(a, 0, 255).astype(np.uint8), 'RGBA')
    cap = lifted(cap)
    cap = cap.crop(cap.getbbox())
    a = np.asarray(cap)[..., 3] > 128
    # the cap: rows down to where the solid narrows to the stalk (the widest row's span, then the first row below it under 40% as wide)
    span = a.sum(1)
    wide = int(np.argmax(span))
    rim = next((y for y in range(wide, a.shape[0]) if span[y] < span[wide] * 0.4), a.shape[0])
    stalk_rows = a[min(a.shape[0] - 1, rim + 4):]
    cols = np.where(stalk_rows.any(0))[0]
    sx0, sx1 = (int(cols.min()), int(cols.max())) if len(cols) else (cap.width // 2 - 10, cap.width // 2 + 10)
    # (the cap down to a little below its rim, so the painted stalk's top meets the tiled stalk under it)
    cut = min(cap.height, rim + 30)
    cap = cap.crop((0, 0, cap.width, cut))
    s = CAP_W / cap.width
    cap = cap.resize((CAP_W, round(cap.height * s)), Image.LANCZOS)
    # the stalk under the cap: its span in the frame's last rows (below the leaves and the skirt)
    low = np.asarray(cap)[-4:, :, 3] > 128
    lc = np.where(low.any(0))[0]
    sx0, sx1 = (int(lc.min()), int(lc.max())) if len(lc) else (sx0 * s, sx1 * s)
    sx0, sx1 = sx0 / s, sx1 / s
    xs = np.where(a[wide])[0]
    cells.append((f'cap-{sp}', cap, {'cw': round((xs.max() - xs.min()) / a.shape[1], 4), 'cx': round((xs.min() + xs.max()) / 2 / a.shape[1], 4),
                                     'sx': round((sx0 + sx1) / 2 / a.shape[1], 4), 'sw': round((sx1 - sx0) / a.shape[1], 4),
                                     'rim': round(rim * s / cap.height, 4), 'span': wspan}))
    st = lifted(depurple(key(Image.open(raw / f"{pk['stalk']}.webp")), edge_only=1))
    bb = st.getbbox()
    st = st.crop((0, bb[1], st.width, bb[3])).rotate(90, expand=True)
    k = 48 / st.width
    st = st.resize((48, round(st.height * k)), Image.LANCZOS)
    st = st.crop((0, 0, 48, min(st.height, STALK_H)))
    cells.append((f'stalk-{sp}', st, {}))
W = sum(c.width for _, c, _ in cells) + 2 * len(cells)
H = max(c.height for _, c, _ in cells)
S = Image.new('RGBA', (W, H), (0, 0, 0, 0))
x = 0
for n, c, extra in cells:
    S.alpha_composite(c, (x, 0))
    frames[n] = {'x': x, 'y': 0, 'w': c.width, 'h': c.height, **extra}
    x += c.width + 2
out = ROOT / 'src/assets/props/bounce.webp'
S.save(out, 'WEBP', quality=88, method=6)
(ROOT / 'src/game/bounceAtlasData.ts').write_text(
    '/** Generated by tools/art/hfground/packbounce.py (hf-art-ground round 3, 2026-10-29): the bounce plants painted on Hugging Face in the\n'
    ' * kit style. cap-<species>: the cap, its top row the collision line; cw/cx the widest span and its middle, sx/sw the stalk under it,\n'
    ' * as shares of the frame\'s width; rim: where the cap meets its stalk, a share of the frame\'s height. stalk-<species>: one repeat of\n'
    ' * the stalk, upright, tiling downward. span: the cap\'s widest span over the platform\'s width. Each world its own plant (cap-w<N>). */\n'
    'export interface BounceFrame { x: number; y: number; w: number; h: number; cw?: number; cx?: number; sx?: number; sw?: number; rim?: number; span?: number }\n'
    "export const BOUNCE_URL = new URL('../assets/props/bounce.webp', import.meta.url).href;\n"
    f'export const BOUNCE_FRAMES: Record<string, BounceFrame> = {json.dumps(frames)};\n')
print(out, out.stat().st_size, json.dumps(frames))
