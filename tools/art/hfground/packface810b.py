"""Pack Worlds 8-10's bank-face pieces (HF jobs hfg-face-810, hfg-face-89b: each painted into its world's own soil) into
src/assets/props/faces810.webp and src/game/w810FaceData.ts (hf-art-ground, 2026-10-30; W8-10 inventory item 3). Each piece keeps its
middle and is feathered out to nothing at its edges (an ellipse: solid inside 42%, gone by 96%). Drawn by w810FaceArt.ts.
    python3 tools/art/hfground/packface810b.py <raw dir> [<raw dir 2> ...]      (picks: picks-face.json {"<w>": [name, ...]})
picks-face.json's "stones" (World 8's rounded mossy stones for the ledges, on a green key) go on a row of their own, cut to their
outline: FACE810_STONES, drawn by w810FaceArt.ts drawW8Stones (2026-10-30, in place of the white stalagmites, which read as thorns).
A pick may name a square to take, as fractions of the take: "<name>@<cx>,<cy>,<size>" (a piece painted off the middle).
"""
import json, sys
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
from keying import gkey  # noqa: E402

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
raws = [Path(a) for a in sys.argv[1:]]
picks = json.loads((HERE / 'picks-face.json').read_text())
PX = 384
yy, xx = np.mgrid[0:PX, 0:PX].astype(np.float32)
r = np.hypot((xx + 0.5 - PX / 2) / (PX / 2), (yy + 0.5 - PX / 2) / (PX / 2))
t = np.clip((0.96 - r) / (0.96 - 0.42), 0, 1)
mask = Image.fromarray((t * t * (3 - 2 * t) * 255).astype(np.uint8))
stones = picks.pop('stones', [])
n = sum(len(v) for v in picks.values())
cols = 5
rows = (n + cols - 1) // cols
S = Image.new('RGBA', (cols * (PX + 2), rows * (PX + 2) + (200 if stones else 0)), (0, 0, 0, 0))
frames, k = {}, 0
for w, names in picks.items():
    frames[w] = []
    for pick in names:
        name, _, box = pick.partition('@')
        src = next(r / f'{name}.webp' for r in raws if (r / f'{name}.webp').exists())
        im = Image.open(src).convert('RGB')
        if box:
            cx, cy, sz = (float(v) for v in box.split(','))
            W, H = im.size
            im = im.crop((round((cx - sz / 2) * W), round((cy - sz / 2) * H), round((cx + sz / 2) * W), round((cy + sz / 2) * H)))
        im = im.resize((PX, PX), Image.LANCZOS).convert('RGBA')
        im.putalpha(mask)
        x, y = (k % cols) * (PX + 2), (k // cols) * (PX + 2)
        S.alpha_composite(im, (x, y))
        frames[w].append({'x': x, 'y': y, 'w': PX, 'h': PX})
        k += 1
sframes, sx = [], 0
for name in stones:
    src = next(r / f'{name}.webp' for r in raws if (r / f'{name}.webp').exists())
    im = gkey(Image.open(src))
    im = im.crop(im.getbbox())
    im = im.resize((round(im.width * 190 / im.height), 190), Image.LANCZOS) if im.height > 190 else im
    S.alpha_composite(im, (sx, rows * (PX + 2)))
    sframes.append({'x': sx, 'y': rows * (PX + 2), 'w': im.width, 'h': im.height})
    sx += im.width + 2
out = ROOT / 'src/assets/props/faces810.webp'
S.save(out, 'WEBP', quality=86, method=6)
(ROOT / 'src/game/w810FaceData.ts').write_text(
    '/** Generated by tools/art/hfground/packface810b.py (hf-art-ground, 2026-10-30): Worlds 8-10\'s bank-face pieces, each painted into\n'
    ' * the world\'s own soil and feathered at its edges. Drawn by w810FaceArt.ts. */\n'
    "export const FACE810_URL = new URL('../assets/props/faces810.webp', import.meta.url).href;\n"
    f'export const FACE810_FRAMES: Record<number, Array<{{ x: number; y: number; w: number; h: number }}>> = {json.dumps(frames)};\n'
    f'export const FACE810_STONES: Array<{{ x: number; y: number; w: number; h: number }}> = {json.dumps(sframes)};\n')
print(S.size, out.stat().st_size)
