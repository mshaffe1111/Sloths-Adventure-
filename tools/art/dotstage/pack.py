"""Pack the cut pieces of Dot's netting flight (cut.py --names) into their own atlas, and encode its backgrounds.

    python3 -I tools/art/dotstage/pack.py <dir with the dotst-back-* sheets>

Writes src/assets/props/dot-props.webp and src/game/dotPropsData.ts (shelf packing, tallest first), and the five painted backgrounds
as src/assets/backdrops/dot-far-1/2.webp and dot-near-1/2/3.webp. Every file stays far under the 4 MiB limit."""
import json, sys
from pathlib import Path
from PIL import Image

H = Path(__file__).resolve().parent
ROOT = H.parents[2]
NAMES = json.loads((H / 'names.json').read_text())
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else None
SCALE = 0.55
W = 2048
PAD = 4

pieces = []
for sheet, names in NAMES.items():
    for n in names:
        im = Image.open(H / 'cut' / f'{n}.png').convert('RGBA')
        im = im.resize((max(1, round(im.width * SCALE)), max(1, round(im.height * SCALE))), Image.LANCZOS)
        pieces.append((n, im))
pieces.sort(key=lambda t: -t[1].height)
frames = {}
x = y = row = 0
for n, im in pieces:
    if x + im.width > W:
        x, y, row = 0, y + row + PAD, 0
    frames[n] = (x, y, im.width, im.height)
    x += im.width + PAD
    row = max(row, im.height)
atlas = Image.new('RGBA', (W, y + row), (0, 0, 0, 0))
for n, im in pieces:
    fx, fy, _, _ = frames[n]
    atlas.paste(im, (fx, fy))
out = ROOT / 'src/assets/props/dot-props.webp'
atlas.save(out, 'WEBP', quality=86, method=6)
print('atlas', atlas.size, out.stat().st_size, 'bytes')
lines = [
    "// generated by tools/art/dotstage/pack.py from the art for Dot's netting flight (Hugging Face, 2026-10-25): where each piece sits in dot-props.webp",
    'export interface DotPropFrame { x: number; y: number; w: number; h: number }',
    'export const DOT_PROP_FRAMES = {',
]
for n in sorted(frames):
    fx, fy, fw, fh = frames[n]
    lines.append(f'  {n}: {{ x: {fx}, y: {fy}, w: {fw}, h: {fh} }},')
lines.append('} satisfies Record<string, DotPropFrame>;')
(ROOT / 'src/game/dotPropsData.ts').write_text('\n'.join(lines) + '\n')

if SRC:
    for src, dst in [('dotst-back-far-11', 'dot-far-1'), ('dotst-back-far-22', 'dot-far-2'), ('dotst-back-near-11', 'dot-near-1'),
                     ('dotst-back-near-22', 'dot-near-2'), ('dotst-back-near-33', 'dot-near-3')]:
        im = Image.open(SRC / f'{src}.png').convert('RGB')
        o = ROOT / f'src/assets/backdrops/{dst}.webp'
        im.save(o, 'WEBP', quality=80, method=6)
        print(dst, im.size, o.stat().st_size, 'bytes')
