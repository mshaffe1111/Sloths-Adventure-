"""Cut a Wan clip of a story plate into its moving parts (hf-cutscenes, 2026-10-31), for src/game/livePlates.ts.

    python3 -I tools/art/hfstory/livecut.py <plate> <frames dir> [first] [budget MB]
-> src/assets/story/live/<plate>.webp, src/game/livePlateData.ts (that plate's row), and a review strip in /tmp

- a seamless loop: N frames at 8 a second (every 2nd clip frame), each one a crossfade of frame i and frame i+N, so the last runs
  into the first with no jump (the classic cinemagraph loop);
- colour held to the painting: each frame's broad colour (a heavy blur) is swapped for the still plate's, so only the motion shows,
  never a shift in tone where the moving patch meets the still painting;
- only where it moves: a soft mask of the pixels that change over the loop; the sheet holds the box around them;
- small: the sheet is scaled so all its frames come to `budget` MB decoded or less (8 by default: the lead, 2026-10-31).
The clip was made from the plate resized to 704 x 752 (its whole picture, livestarts/).
"""
import json, re, sys
from pathlib import Path
import numpy as np
from PIL import Image, ImageFilter
from scipy import ndimage

GAME = Path(__file__).resolve().parents[3]
plate, src = sys.argv[1], Path(sys.argv[2])
first = int(sys.argv[3]) if len(sys.argv) > 3 else 1
budget = float(sys.argv[4]) if len(sys.argv) > 4 else 8.0
# a box (shares of the picture: x0,y0,x1,y1) that never moves: a painted figure stays the sharp painting, never the soft clip
keep = [float(v) for v in sys.argv[5].split(',')] if len(sys.argv) > 5 else None
N, STEP, FPS, COLS = 12, 2, 8, 4

P = Image.open(GAME / f'src/assets/story/plates/{plate}.webp').convert('RGB')
PW, PH = P.size
fs = sorted(src.glob('*.webp')) or sorted(src.glob('*.png'))
F = [np.asarray(Image.open(f).convert('RGB')).astype(np.float32) for f in fs]
h, w, _ = F[0].shape
idx = [first + STEP * i for i in range(2 * N)]
assert idx[-1] < len(F), f'{len(F)} frames, need {idx[-1] + 1}'
# the plate at the clip's size, its broad colour
pl = np.asarray(P.resize((w, h), Image.LANCZOS)).astype(np.float32)
blur = lambda a: ndimage.gaussian_filter(a, (18, 18, 0))
plb = blur(pl)
loop = []
for i in range(N):
    a = i / N
    f = F[idx[i]] * a + F[idx[i + N]] * (1 - a)
    f = f - blur(f) + plb
    loop.append(np.clip(f, 0, 255))
A = np.stack(loop)
move = A.mean(axis=3).std(axis=0)
# (broad soft regions, not blotches: the motion's share in a wide neighbourhood, so a whole sky moves, never patches of it)
mask = ndimage.binary_opening(move > 2.5, iterations=1).astype(np.float32)
dens = ndimage.gaussian_filter(mask, 22)
soft = np.clip((dens - 0.08) / 0.17, 0, 1)
if keep:
    kx0, ky0, kx1, ky1 = keep
    hold = np.zeros_like(soft)
    hold[round(ky0 * h):round(ky1 * h), round(kx0 * w):round(kx1 * w)] = 1
    soft = soft * (1 - np.clip(ndimage.gaussian_filter(hold, 6) * 2, 0, 1))
soft = ndimage.gaussian_filter(soft, 6)
cover = (soft > 0.03).mean()
ys, xs = np.where(soft > 0.03)
if not len(ys):
    sys.exit(f'{plate}: nothing moves')
y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
bw, bh = x1 - x0, y1 - y0
# the sheet's scale: N frames under the budget, never above the clip's own size
k = min(1.0, (budget * 1e6 / 4 / N / (bw * bh)) ** 0.5)
fw, fh = max(8, round(bw * k)), max(8, round(bh * k))
rows = (N + COLS - 1) // COLS
assert fw * COLS <= 4096 and fh * rows <= 4096
sheet = Image.new('RGBA', (fw * COLS, fh * rows), (0, 0, 0, 0))
al = (soft[y0:y1, x0:x1] * 255).astype(np.uint8)
for i in range(N):
    im = Image.fromarray(np.dstack([A[i, y0:y1, x0:x1].astype(np.uint8), al]), 'RGBA').resize((fw, fh), Image.LANCZOS)
    sheet.paste(im, ((i % COLS) * fw, (i // COLS) * fh))
out = GAME / 'src/assets/story/live'
out.mkdir(parents=True, exist_ok=True)
sheet.save(out / f'{plate}.webp', 'WEBP', quality=80, method=6)
# where the box lies on the plate, in the game's 1024-wide units from the top of the plate's scene part (its bottom 1024:572)
u = 1024 / PW
base = PH - PW * 572 / 1024
sx, sy = PW / w, PH / h
meta = dict(n=N, cols=COLS, w=fw, h=fh, fps=FPS, x=round(x0 * sx * u, 2), y=round((y0 * sy - base) * u, 2),
            pw=round(bw * sx * u, 2), ph=round(bh * sy * u, 2))
mb = fw * COLS * fh * rows * 4 / 1e6
print(plate, meta, f'moving {cover:.0%}', f'{(out / f"{plate}.webp").stat().st_size // 1024} KB', f'{mb:.1f} MB decoded')

DATA = GAME / 'src/game/livePlateData.ts'
old = json.loads(re.search(r'LIVE_PLATES: Record<string, LivePlate> = (\{.*?\});', DATA.read_text(), re.S).group(1))
old[plate] = meta
DATA.write_text(f'''/** Generated by the live-plate cutters (Wan clips of the story plates, only the parts that move: tools/art/hfstory/livecut.py). Do not edit by hand. */
export interface LivePlate {{
  n: number; cols: number; w: number; h: number; fps: number;
  /** where the clip sits on the plate, in 1024-wide units from the top of the plate's scene part (its bottom 1024:572) */
  x: number; y: number; pw: number; ph: number;
}}
export const LIVE_PLATES: Record<string, LivePlate> = {json.dumps(old, indent=1)};
''')
# review: the mask and four frames
rv = Image.new('RGB', (w * 3, h))
rv.paste(Image.fromarray((soft * 255).astype(np.uint8)).convert('RGB'), (0, 0))
rv.paste(Image.fromarray(A[0].astype(np.uint8)), (w, 0))
rv.paste(Image.fromarray(A[N // 2].astype(np.uint8)), (2 * w, 0))
rv.save(f'/tmp/claude-0/livecut-{plate}.jpg', quality=80)
