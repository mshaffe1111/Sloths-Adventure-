"""Pack Pokey's rope frames into the game (2026-10-29): src/assets/hero/hero-rope.webp + src/game/heroRopeData.ts.

    python3 -I tools/art/rope/pack.py [picks.json]

picks.json (beside this file): {"cycle": [frame, ...], "still": frame, "stride_px": sheet px of travel per cycle, "source": "..."}; a frame
is a cut-out in tools/art/rope/frames/ (cut.py: f1..f7 from the Gemini sheet) or tools/art/rope/clipframes/ (cutclip.py: clip frames),
each with its grip (`gy`, the rope's middle at the paws) and torso middle (`ax`) in the meta.json beside it. Frames are packed in one
row, in the order first used, at the sheet's own pixels (his standing height ROPE_STAND_PX, measured from the sheet's standing cell).
"""
import json, sys
from pathlib import Path

from PIL import Image

H = Path(__file__).resolve().parent
GAME = H.parents[2]
GAP = 2


def main(picks_path):
    picks = json.loads(Path(picks_path).read_text())
    metas = {}
    for d in ('frames', 'clipframes'):
        mp = H / d / 'meta.json'
        if mp.exists():
            m = json.loads(mp.read_text())
            metas[d] = m
    stand = metas['frames']['stand_px']
    order = []
    for n in picks['cycle'] + [picks['still']]:
        if n not in order:
            order.append(n)

    def find(n):
        for d, m in metas.items():
            if n in m:
                return H / d / f'{n}.png', m[n], m.get('scale', 1.0)
        raise KeyError(n)

    ims, fr = [], {}
    x = 0
    for n in order:
        p, m, sc = find(n)
        im = Image.open(p).convert('RGBA')
        if sc != 1.0:
            im = im.resize((round(im.width * sc), round(im.height * sc)), Image.LANCZOS)
        ims.append((x, im))
        fr[n] = {'x': x, 'y': 0, 'w': im.width, 'h': im.height, 'ax': round(m['ax'] * sc, 1), 'gy': round(m['gy'] * sc, 1)}
        x += im.width + GAP
    sheet = Image.new('RGBA', (x - GAP, max(im.height for _, im in ims)), (0, 0, 0, 0))
    for xx, im in ims:
        sheet.alpha_composite(im, (xx, 0))
    out = GAME / 'src/assets/hero/hero-rope.webp'
    sheet.save(out, 'WEBP', quality=92, method=6)
    name = lambda n: f'r{n}' if n[0].isdigit() else n  # noqa: E731
    lines = [f"// generated by tools/art/rope/pack.py (2026-10-29) from {picks['source']}",
             '// Pokey crossing a shimmy rope hand over hand; the drawn rope was cut out of the pictures (tools/art/rope/cut.py), so he holds the game\'s own.',
             '// ax: the middle of his torso; gy: the rope\'s middle where his paws grip it (both in sheet px, from the picture\'s top left)',
             'export const ROPE_FRAMES = {']
    for n in order:
        f = fr[n]
        lines.append(f"  {name(n)}: {{ x: {f['x']}, y: 0, w: {f['w']}, h: {f['h']}, ax: {f['ax']}, gy: {f['gy']} }},")
    lines += ['} as const;',
              '/** the hand-over-hand cycle while he creeps along, in order (the first is both paws on the rope) */',
              'export const ROPE_CYCLE = [' + ', '.join(f"'{name(n)}'" for n in picks['cycle']) + '] as const;',
              '/** hanging still from one paw */',
              f"export const ROPE_STILL = '{name(picks['still'])}' as const;",
              '/** his standing height in this sheet\'s px (the Gemini sheet\'s standing cell): sizes him against the standing hero */',
              f'export const ROPE_STAND_PX = {stand};',
              '/** how far one cycle carries him along the rope, in sheet px */',
              f"export const ROPE_STRIDE_PX = {picks['stride_px']};", '']
    (GAME / 'src/game/heroRopeData.ts').write_text('\n'.join(lines))
    print(out, out.stat().st_size, sheet.size)


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else H / 'picks.json')
