"""The shimmy rope's painted pieces (2026-10-29), cut from art already in the game so the rope is painted, not stroked:

  tile  World 2's painted rope (its kit liana, src/assets/kits/w2.webp, the plain twisted stretch between its two knots), five turns of
        the twist (the twist repeats every ~20.8 px), cut where the two ends match best so it tiles without a seam, and turned to lie
        across (the rope runs left to right in the sheet)
  post  the right-hand post of World 2's rope-swing frame (w2-props.webp swingFrame): a round pole with its end cap and an X lashing
        near the top, where the rope is tied on; the frame's beam is cut off at the lashing

    python3 -I tools/art/rope/pack_kit.py   -> src/assets/props/rope-kit.webp + src/game/ropeKitData.ts
"""
import json
from pathlib import Path

import numpy as np
from PIL import Image

H = Path(__file__).resolve().parent
GAME = H.parents[2]
KIT = json.loads((GAME / 'src/game/kitAtlasData.ts').read_text().split('= ', 1)[1].rstrip().rstrip(';'))
PERIOD = 20.8
TURNS = 5


def tile():
    f = KIT['2']['liana']
    im = Image.open(GAME / 'src/assets/kits/w2.webp').convert('RGBA').crop((f['x'], f['y'], f['x'] + f['w'], f['y'] + f['h']))
    a = np.asarray(im).astype(float)
    L = round(PERIOD * TURNS)
    # the plain stretch runs from about y 222 to 505; pick the start whose row best matches the row L further down
    best = min(range(224, 500 - L), key=lambda y: np.abs(a[y, 30:72] - a[y + L, 30:72]).sum())
    # the strand's columns (alpha over the whole stretch), with a pixel to spare
    al = a[best:best + L, :, 3]
    cols = np.flatnonzero((al > 40).mean(axis=0) > 0.5)
    x0, x1 = cols.min() - 1, cols.max() + 2
    t = im.crop((x0, best, x1, best + L))
    # lying across: the rope's top in the picture becomes its left end
    t = t.transpose(Image.ROTATE_90)
    # the strand's middle and thickness (in the turned tile: rows), from where it is solid
    ta = np.asarray(t)[:, :, 3]
    rows = np.flatnonzero((ta > 128).mean(axis=1) > 0.6)
    return t, {'mid': round(float((rows.min() + rows.max() + 1) / 2), 1), 'thick': int(rows.max() + 1 - rows.min()), 'start': best}


def post():
    w2 = Image.open(GAME / 'src/assets/props/w2-props.webp').convert('RGBA')
    sx, sy = 660, 0  # swingFrame in W2_FRAMES
    p = w2.crop((sx + 300, sy, sx + 338, sy + 352))
    a = np.array(p)
    # the beam's stubs either side of the lashing (rows 20-64): keep only what lies inside the lashing's outline
    pole = (a[100:300, :, 3] > 128).mean(axis=0) > 0.5
    px = np.flatnonzero(pole)
    lash = a[20:66, :, 3] > 128
    for x in range(a.shape[1]):
        if x < px.min() - 5 or x > px.max() + 5:
            a[20:66, x, 3] = 0
    p = Image.fromarray(a)
    ys = np.flatnonzero((a[:, :, 3] > 128).any(axis=1))
    # where the rope ties on (the middle of the lashing) and the pole's own width and middle
    return p, {'tie': 43, 'top': int(ys.min()), 'poleL': int(px.min()), 'poleR': int(px.max() + 1), 'lash': [20, 66], 'unused': int(lash.sum())}


if __name__ == '__main__':
    t, tm = tile()
    p, pm = post()
    W = max(t.width, p.width) + 0
    sheet = Image.new('RGBA', (t.width + 4 + p.width, max(t.height, p.height)), (0, 0, 0, 0))
    sheet.alpha_composite(t, (0, 0))
    sheet.alpha_composite(p, (t.width + 4, 0))
    out = GAME / 'src/assets/props/rope-kit.webp'
    sheet.save(out, 'WEBP', quality=90, method=6)
    frames = {
        'tile': {'x': 0, 'y': 0, 'w': t.width, 'h': t.height, 'mid': tm['mid'], 'thick': tm['thick']},
        'post': {'x': t.width + 4, 'y': 0, 'w': p.width, 'h': p.height, 'top': pm['top'], 'tie': pm['tie'],
                 'poleL': pm['poleL'], 'poleR': pm['poleR']},
    }
    ts = ('// generated by tools/art/rope/pack_kit.py (2026-10-29) from art already in the game: where the shimmy rope\'s painted pieces sit in rope-kit.webp\n'
          '// tile: World 2\'s painted twisted rope (its kit liana), five turns of the twist cut to tile without a seam, lying left to right;\n'
          '//   mid: the strand\'s middle (rows), thick: the strand\'s thickness (rows)\n'
          '// post: the right-hand post of World 2\'s rope-swing frame; top: the top of its cap, tie: the middle of its X lashing (where the rope is\n'
          '//   tied on), poleL/poleR: the pole\'s sides (columns)\n'
          'export const ROPE_KIT = {\n' + ''.join(f'  {k}: {{ ' + ', '.join(f'{a}: {b}' for a, b in v.items()) + ' },\n' for k, v in frames.items()) +
          '} as const;\n')
    (GAME / 'src/game/ropeKitData.ts').write_text(ts)
    print(out, out.stat().st_size, sheet.size, frames, 'tile start row', tm['start'])
