"""The Shadow Prowler's Wan clips -> the game's atlas (src/assets/enemies/prowler-anim.webp + src/game/prowlerAnimData.ts).

Same as the croc's packer: each clip is keyed off its grey, every frame of a clip shares one box, and the frames are sized so the cat is
the same size as the old painted frames, times UP. The anchor (the middle of the body on the ground line) is the old frame's anchor
carried through the collared start pose and the video job's crop, so the weak points measured off the old frames still sit right.

  python3 pack_anim.py
"""
import json, re, sys
from pathlib import Path
import numpy as np
from PIL import Image
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / 'train'))
from clips import key  # noqa: E402

HERE = Path(__file__).resolve().parent
GAME = __import__('pathlib').Path(str(__import__('pathlib').Path(__file__).resolve().parents[3]))
UP = 2.0
OLD = json.loads(re.search(r'PROWLER_FRAMES: Record<string, BossFrame> = (\{.*\});', (GAME / 'src/game/prowlerAtlasData.ts').read_text()).group(1))
# clip -> (old frame it started from, the collared start picture)
START = {'idle': ('idle', 'idle-d1'), 'walk': ('w_1', 'w_1-d1'), 'pounce': ('viper', 'viper-s2'), 'roar': ('alert', 'alert-d1'),
         'gallop11': ('run_0', 'gallop-start'), 'swat3': ('idle', 'idle-d1'),
         'hurt': ('hurt', 'hurt-s2'), 'stagger': ('hurt', 'hurt-s2'), 'defeated': ('hurt', 'hurt-s2')}
SIZE = {'roar': (768, 576), 'pounce': (832, 576)}
R = lambda a, b, s=1: list(range(a, b, s))
SEL = {
    'idle': R(8, 48, 2),
    'walk': R(6, 44, 2),
    'crouch': {'clip': 'pounce', 'frames': R(0, 7)},
    'air': {'clip': 'pounce', 'frames': R(7, 31)},
    'land': {'clip': 'pounce', 'frames': R(31, 49, 2)},
    'dash': {'clip': 'gallop11', 'frames': R(0, 28, 2)},
    'claw': {'clip': 'swat3', 'frames': R(3, 13)},
    'bite': {'clip': 'pounce', 'frames': R(40, 49, 2)},
    'roar': R(0, 25, 2),
    'swipe': {'clip': 'swat3', 'frames': R(26, 38, 2)},
    'hurt': R(0, 14),
    'stagger': R(4, 22, 2),
    'defeated': R(0, 22),
}
SEQ = {k: (v if isinstance(v, dict) else {'clip': k, 'frames': v}) for k, v in SEL.items()}
NEED: dict[str, set] = {}
for v in SEQ.values():
    NEED.setdefault(v['clip'], set()).update(v['frames'])


def bbox(a):
    ys, xs = np.nonzero(a > 128)
    return xs.min(), ys.min(), xs.max() + 1, ys.max() + 1


def prep_map(w, h, W0=1024, H0=1024):
    """the video job's crop: start-pose px -> clip px, as (offset x, offset y, scale)"""
    want = w / h
    cw, ch = (W0, int(W0 / want)) if W0 / H0 > want else (int(H0 * want), H0)
    cW, cH = max(cw, W0), max(ch, H0)
    px, py = (cW - W0) // 2, (cH - H0) // 2
    x0, y0 = (cW - cw) // 2, (cH - ch) // 2
    return px - x0, py - y0, w / cw


frames = {}
for name, idxs in NEED.items():
    idxs = sorted(idxs)
    oldn, pic = START[name]
    o = OLD[oldn]
    a0 = key(np.asarray(Image.open(HERE / f'dl/collared/{pic}.png').convert('RGB')))
    bx0, by0, bx1, by1 = bbox(a0)
    ratio = (bx1 - bx0) / o['w']
    axi, ayi = bx0 + o['ax'] * ratio, by0 + o['ay'] * ratio
    w, h = SIZE.get(name, (832, 480))
    ox, oy, sc = prep_map(w, h)
    axc, ayc = (axi + ox) * sc, (ayi + oy) * sc
    f = UP / (ratio * sc)  # atlas px per clip px
    ims = []
    for i in idxs:
        rgb = np.asarray(Image.open(HERE / f'vids/{name}/{name}_{i:03d}.png').convert('RGB'))
        ims.append((i, np.dstack([rgb, key(rgb)])))
    U = [bbox(im[..., 3]) for _, im in ims]
    x0, y0 = min(u[0] for u in U), min(u[1] for u in U)
    x1, y1 = max(u[2] for u in U), max(u[3] for u in U)
    for i, im in ims:
        c = Image.fromarray(im[y0:y1, x0:x1].astype(np.uint8), 'RGBA')
        c = c.resize((max(1, round(c.width * f)), max(1, round(c.height * f))), Image.LANCZOS)
        tb = c.getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox()
        c = c.crop(tb)
        frames[f'{name}_{i:03d}'] = (c, (axc - x0) * f - tb[0], (ayc - y0) * f - tb[1])
    print(name, len(idxs), 'frames', frames[f'{name}_{idxs[0]:03d}'][0].size, 'ratio', round(ratio, 2), 'f', round(f, 3))

W, pad = 4096, 2
order = sorted(frames, key=lambda n: -frames[n][0].height)
x = y = rowh = 0
pos = {}
for n in order:
    im = frames[n][0]
    if x + im.width + pad > W:
        x = 0; y += rowh + pad; rowh = 0
    pos[n] = (x, y); x += im.width + pad; rowh = max(rowh, im.height)
H = y + rowh
atlas = Image.new('RGBA', (W, H), (0, 0, 0, 0))
for n, (px, py) in pos.items():
    atlas.paste(frames[n][0], (px, py))
atlas.save(GAME / 'src/assets/enemies/prowler-anim.webp', 'WEBP', quality=82, method=6)
out = {n: {'x': pos[n][0], 'y': pos[n][1], 'w': frames[n][0].width, 'h': frames[n][0].height,
           'ax': round(frames[n][1], 1), 'ay': round(frames[n][2], 1)} for n in sorted(frames)}
ts = ('/** Generated by scratchpad/prowl/pack_anim.py from the Wan 2.2 clips of the Shadow Prowler in his iron collar. Frames face RIGHT;\n'
      ' * ax/ay is the middle of the body on the ground line, sized UP = %s times the old painted frames (draw at k / UP). */\n' % UP)
ts += 'import type { BossFrameRect } from \'./paintedBoss.ts\';\n'
ts += f'export const PROWLER_ANIM_UP = {UP};\n'
ts += f'export const PROWLER_ANIM_SIZE = {{ w: {W}, h: {H} }};\n'
ts += '/** the frame names of each move, in order */\n'
ts += 'export const PROWLER_CLIPS = ' + json.dumps({k: [f"{v['clip']}_{i:03d}" for i in v['frames']] for k, v in SEQ.items()}) + ' as const satisfies Record<string, readonly string[]>;\n'
ts += 'export const PROWLER_ANIM_FRAMES: Record<string, BossFrameRect> = ' + json.dumps(out) + ';\n'
(GAME / 'src/game/prowlerAnimData.ts').write_text(ts)
print('atlas', W, H, len(frames), 'frames', round((GAME / 'src/assets/enemies/prowler-anim.webp').stat().st_size / 1024), 'KB')
