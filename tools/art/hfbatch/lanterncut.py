"""Key 8-4 Lantern Run's Hugging Face picks off the magenta (w6to10/geminicut.py cut_cell, then the fringe despill chairscut.py uses), trim,
scale and pack them into src/assets/w8/lantern.webp with src/game/w8LanternAtlas.ts (frames and anchors), and write the review sheet
(every pick on dark and on mid-grey).
    python3 -I tools/art/hfbatch/lanterncut.py <takes dir> <review.jpg> name=pick:height[:ax,ay] ...
  e.g. jar=jar-s60-17:96 jarDim=jardim-s70-5:96 mothOpen=moth-open-s72-5:70 mothUp=moth-up-s72-5:70
  height: the packed height (px); anchors are the bottom middle unless given as shares of the trimmed picture.
"""
import json, sys
from pathlib import Path
import numpy as np
from PIL import Image, ImageDraw
from scipy import ndimage
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'w6to10'))
from geminicut import cut_cell  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
TAKES, REVIEW = Path(sys.argv[1]), Path(sys.argv[2])
picks = []
for arg in sys.argv[3:]:
    name, rest = arg.split('=')
    parts = rest.split(':')
    anchor = tuple(float(v) for v in parts[2].split(',')) if len(parts) > 2 else (0.5, 1.0)
    picks.append((name, parts[0], int(parts[1]), anchor))


def cut(stem):
    src = Image.open(TAKES / f'{stem}.webp').convert('RGB')
    sp = cut_cell(src, 'magenta', {})
    sp = sp.crop(sp.getchannel('A').getbbox())
    a = np.asarray(sp).astype(np.float32)
    band = ndimage.binary_dilation(a[..., 3] < 128, iterations=4) & (a[..., 3] > 0)
    ex = np.clip(np.minimum(a[..., 0], a[..., 2]) - a[..., 1] - 6, 0, None) * band
    a[..., 0] -= ex
    a[..., 2] -= ex
    return Image.fromarray(np.clip(a, 0, 255).astype(np.uint8), 'RGBA')


cells = []
for name, stem, h, anchor in picks:
    im = cut(stem)
    k = h / im.height
    im = im.resize((max(1, round(im.width * k)), h), Image.LANCZOS)
    cells.append((name, im, anchor))
W = sum(c[1].width + 4 for c in cells)
H = max(c[1].height for c in cells)
sheet = Image.new('RGBA', (W, H), (0, 0, 0, 0))
frames = {}
x = 0
for name, im, (axs, ays) in cells:
    sheet.alpha_composite(im, (x, 0))
    frames[name] = {'x': x, 'y': 0, 'w': im.width, 'h': im.height, 'ax': round(im.width * axs, 1), 'ay': round(im.height * ays, 1)}
    x += im.width + 4
out = ROOT / 'src/assets/w8/lantern.webp'
out.parent.mkdir(parents=True, exist_ok=True)
sheet.save(out, 'WEBP', quality=90, method=6)
ts = ROOT / 'src/game/w8LanternAtlas.ts'
ts.write_text('// generated by tools/art/hfbatch/lanterncut.py from 8-4 Lantern Run\'s Hugging Face picks (reference/prop-sheets/qa-notes/8-4-art):\n'
              '// where each piece sits in src/assets/w8/lantern.webp, and its anchor (ax, ay: drawn at its foot unless said)\n'
              'export interface LanternFrame { x: number; y: number; w: number; h: number; ax: number; ay: number }\n'
              f'export const LANTERN_FRAMES: Record<string, LanternFrame> = {json.dumps(frames)};\n')
print(out, sheet.size, out.stat().st_size)

# the review: each pick on dark and mid-grey, at its packed size and at about phone size (x0.5)
rows = []
for name, im, _ in cells:
    row = Image.new('RGB', (im.width * 2 + im.width + 60, im.height + 30), (24, 24, 24))
    d = ImageDraw.Draw(row)
    d.text((4, 2), name, fill=(255, 230, 0))
    for i, col in enumerate(((20, 16, 24), (128, 128, 128))):
        bg = Image.new('RGBA', im.size, col + (255,))
        bg.alpha_composite(im)
        row.paste(bg.convert('RGB'), (i * (im.width + 20), 24))
    small = im.resize((max(1, im.width // 2), max(1, im.height // 2)), Image.LANCZOS)
    bg = Image.new('RGBA', small.size, (20, 16, 24, 255))
    bg.alpha_composite(small)
    row.paste(bg.convert('RGB'), (2 * (im.width + 20), 24))
    rows.append(row)
R = Image.new('RGB', (max(r.width for r in rows), sum(r.height for r in rows)), (24, 24, 24))
y = 0
for r in rows:
    R.paste(r, (0, y))
    y += r.height
REVIEW.parent.mkdir(parents=True, exist_ok=True)
R.save(REVIEW, 'JPEG', quality=88)
print(REVIEW, R.size)
