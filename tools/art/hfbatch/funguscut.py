"""Cut World 8's fungus-step takes (2026-10-31; jobs.txt hfb-w8fungus-r1b) into src/assets/w6to10/props-made/w8fungus.webp and
src/game/w8FungusData.ts: magenta keyed out (with its spill), trimmed, packed side by side; each frame's walkTop is the first row whose
opaque run is over 60% of the frame's width (the flat top he stands on; the moss take's mushrooms stand above it).
    python3 -I tools/art/hfbatch/funguscut.py <takes dir>
"""
import json, sys
from pathlib import Path
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[3]
TAKES = Path(sys.argv[1])
PICKS = {'plain': 'bracket-s62-17.png', 'moss': 'bracket-moss-s62-17.png'}
OUT_W = 300


def key(im):
    a = np.asarray(im.convert('RGB')).astype(np.int16)
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    mag = (r - g) + (b - g)  # high where magenta
    alpha = np.clip(255 - (mag - 140) * 3, 0, 255).astype(np.uint8)
    # spill: pull the magenta out of the edge pixels
    edge = (alpha > 0) & (alpha < 255)
    a2 = a.copy()
    a2[..., 0] = np.where(edge, np.minimum(r, g + 40), r)
    a2[..., 2] = np.where(edge, np.minimum(b, g + 60), b)
    out = np.dstack([np.clip(a2, 0, 255).astype(np.uint8), alpha])
    return Image.fromarray(out, 'RGBA')


frames, ims = {}, []
x = 0
for name, fn in PICKS.items():
    im = key(Image.open(TAKES / fn))
    im = im.crop(im.getbbox())
    im = im.resize((OUT_W, round(OUT_W * im.height / im.width)), Image.LANCZOS)
    al = np.asarray(im)[..., 3] > 128
    top = next(y for y in range(im.height) if al[y].sum() > 0.6 * im.width)
    frames[name] = {'x': x, 'y': 0, 'w': im.width, 'h': im.height, 'walkTop': top}
    ims.append((x, im))
    x += im.width + 4
H = max(im.height for _, im in ims)
sheet = Image.new('RGBA', (x - 4, H), (0, 0, 0, 0))
for px, im in ims:
    sheet.paste(im, (px, 0))
dst = ROOT / 'src/assets/w6to10/props-made/w8fungus.webp'
sheet.save(dst, 'WEBP', quality=90, method=6)
ts = ROOT / 'src/game/w8FungusData.ts'
ts.write_text('// generated by tools/art/hfbatch/funguscut.py (World 8 fungus steps, HF job hfb-w8fungus-r1b, 2026-10-31): do not edit\n'
              "export const W8_FUNGUS_URL = new URL('../assets/w6to10/props-made/w8fungus.webp', import.meta.url).href;\n"
              f'export const W8_FUNGUS_FRAMES: Record<string, {{ x: number; y: number; w: number; h: number; walkTop: number }}> = {json.dumps(frames)};\n')
print(dst, sheet.size, frames)
