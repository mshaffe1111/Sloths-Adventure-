"""Pack the Jungle Journal's card pictures into one small sheet (src/assets/enemies/journal-cards.webp) and its frames
(src/game/journalCardsData.ts). The crops come from frames.mts: the frame of the art each creature is drawn with today.

The game's clip sheets are 13 to 64 MB once decoded, far too much for a menu page to hold all at once, so each card gets its own
small copy here instead. Run from the repo root: python3 tools/art/journal/pack.py
"""
import json, subprocess
from PIL import Image

BOX = (264, 176)  # each picture fits this (2x the largest card box, so it is sharp on a phone)
PAD = 2
COLS = 6

crops = json.loads(subprocess.check_output(['npx', 'tsx', 'tools/art/journal/frames.mts'], text=True))
sheets = {}
pics = []
for c in crops:
    path = 'src/assets/' + c['sheet']
    if path not in sheets:
        sheets[path] = Image.open(path).convert('RGBA')
    r = c['rect']
    im = sheets[path].crop((r['x'], r['y'], r['x'] + r['w'], r['y'] + r['h']))
    bb = im.getbbox()
    if bb:
        im = im.crop(bb)
    if c['flip']:
        im = im.transpose(Image.FLIP_LEFT_RIGHT)
    k = min(BOX[0] / im.width, BOX[1] / im.height, 1.0)
    im = im.resize((max(1, round(im.width * k)), max(1, round(im.height * k))), Image.LANCZOS)
    pics.append((c['id'], im))

cw, ch = BOX[0] + PAD * 2, BOX[1] + PAD * 2
rows = (len(pics) + COLS - 1) // COLS
out = Image.new('RGBA', (cw * COLS, ch * rows), (0, 0, 0, 0))
frames = {}
for i, (cid, im) in enumerate(pics):
    x, y = (i % COLS) * cw + PAD, (i // COLS) * ch + PAD
    out.paste(im, (x, y))
    frames[cid] = {'x': x, 'y': y, 'w': im.width, 'h': im.height}
out.save('src/assets/enemies/journal-cards.webp', 'WEBP', quality=86, method=6)

with open('src/game/journalCardsData.ts', 'w') as f:
    f.write('/** Generated by tools/art/journal/pack.py: where each Jungle Journal card picture sits in journal-cards.webp (frames.mts picks them). */\n')
    f.write("export const JOURNAL_CARDS_URL = new URL('../assets/enemies/journal-cards.webp', import.meta.url).href;\n")
    f.write(f'export const JOURNAL_CARDS_SIZE = {{ w: {out.width}, h: {out.height} }};\n')
    f.write('export const JOURNAL_CARDS: Record<string, { x: number; y: number; w: number; h: number }> = ' + json.dumps(frames) + ';\n')
print(out.size, len(frames))
