"""Cut World 10's swing banners (2026-10-29) from the Hugging Face takes (hfbatch/w10swing/props/w10banner-*.png in the bucket
mshaffe111/w5-xfer, brought back with hf_fs attach) into src/assets/w10/swing-banners.webp and src/game/w10SwingArtData.ts: key the
magenta, pull the fringe's red and blue toward its green (no pink rim), trim, pack side by side at their own size (never upscaled).
    python3 tools/art/w10swing/bannercut.py <dir with the takes>
Picks: w10banner-s50-23 all three, w10banner-s65-23 the right one (its left one shows magenta through a rip; its middle one's rip is
wide). Each frame: ax, ring (the middle of the ring it hangs from), capT / capB (the rows between which the plain cloth may stretch).
"""
import sys
from pathlib import Path
import numpy as np
from PIL import Image

SRC = Path(sys.argv[1])
ROOT = Path(__file__).resolve().parents[3]
PICKS = [('w10banner-s50-23', 0), ('w10banner-s50-23', 1), ('w10banner-s50-23', 2), ('w10banner-s65-23', 2)]


def key(a):
    rgb = a[:, :, :3].astype(float)
    r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]
    mag = np.clip(((r + b) / 2 - g - 60) / 90, 0, 1)  # 1 = magenta
    alpha = (1 - mag) * 255
    # (despill: on the fringe, red and blue no higher than green plus a little)
    spill = mag > 0.005
    lim = g + 12
    rgb[..., 0] = np.where(spill, np.minimum(r, lim), r)
    rgb[..., 2] = np.where(spill, np.minimum(b, lim), b)
    # (no blue in iron or red wool: the magenta's cast on the dark iron goes too)
    rgb[..., 2] = np.minimum(rgb[..., 2], rgb[..., 1] + 14)
    out = np.dstack([rgb, alpha]).clip(0, 255).astype(np.uint8)
    # (a pixel more than a third magenta is cut: no pink rim on dark)
    out[alpha < 170] = 0
    return out


cells = []
for name, k in PICKS:
    a = key(np.array(Image.open(SRC / f'{name}.png').convert('RGB')))
    col = a[:, k * 341:(k + 1) * 341]
    ys, xs = np.where(col[:, :, 3] > 40)
    c = col[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
    # (the ring: the middle of the opaque run on its first rows)
    top = np.where(c[:30, :, 3].max(axis=0) > 100)[0]
    ax = float(top.mean())
    cells.append((Image.fromarray(c), ax))

W = sum(c.width for c, _ in cells) + 4 * len(cells)
H = max(c.height for c, _ in cells)
sheet = Image.new('RGBA', (W, H), (0, 0, 0, 0))
frames = []
x = 0
for c, ax in cells:
    sheet.alpha_composite(c, (x, 0))
    h = c.height
    frames.append(f'  {{ x: {x}, y: 0, w: {c.width}, h: {h}, ax: {ax:.1f}, ring: 32, capT: {round(h * 0.3)}, capB: {round(h * 0.66)} }},')
    x += c.width + 4
dst = ROOT / 'src/assets/w10/swing-banners.webp'
sheet.save(dst, quality=90, method=6)
(ROOT / 'src/game/w10SwingArtData.ts').write_text(
    '// generated by tools/art/w10swing/bannercut.py (2026-10-29): where World 10\'s swing banners sit in src/assets/w10/swing-banners.webp\n'
    '// ax: the middle of the ring it hangs from (px from the frame\'s left); ring: that ring\'s middle (px from its top); the plain cloth\n'
    '// between rows capT and capB may stretch, the ring, the crossbar and the torn end keep their painted size\n'
    'export const W10_BANNERS = [\n' + '\n'.join(frames) + '\n] as const;\n')
print(dst, sheet.size, dst.stat().st_size)
