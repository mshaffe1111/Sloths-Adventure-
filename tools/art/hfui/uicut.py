"""Cut the painted menu kit and build the store art (HF shopping list rows 1-4, hf-art-bosses, 2026-10-30), from the hfui1 takes:

  src/assets/ui/ui-kit.webp + src/game/uiKitData.ts     the menu kit, keyed and packed: planks (brown, green, gold; long and small),
                                                         tab chips (off, on), the parchment card in its frame, the story text box,
                                                         a stat tile, the slider track and knob, the lock badge, star slots, 24 icons
  reference/store/                                       the Play Store art: icon-512.png, adaptive icon-fg-432.png and icon-bg-432.png,
                                                         feature-1024x500.png, splash-2732.jpg; and the web app icons in public/
                                                         (pwa-192x192, pwa-512x512, pwa-maskable-512x512, apple-touch-icon)
  reference/prop-sheets/qa-notes/hf-ui/review-*.jpg      every pick on dark and mid-grey, at full and game size

    python3 -I tools/art/hfui/uicut.py <takes dir> <game checkout> <title feature render png> <title square render png>
"""
import json, sys
from pathlib import Path
import numpy as np
from PIL import Image, ImageDraw, ImageFilter

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'hfbosses'))
TAKES, GAME = Path(sys.argv[1]), Path(sys.argv[2])
FEATURE, SQUARE = Path(sys.argv[3]), Path(sys.argv[4])
sys.argv = [sys.argv[0], str(TAKES), str(GAME)]
import bosscut_lib  # noqa: E402
bosscut_lib.QA = GAME / 'reference/prop-sheets/qa-notes/hf-ui'
bosscut_lib.QA.mkdir(parents=True, exist_ok=True)
from bosscut_lib import cut, review  # noqa: E402

PICK = {'buttons': 'kit-buttons-s62-7', 'panels': 'kit-panels-s62-7', 'icons': 'kit-icons-s40-7',
        'icon-bg': 'icon-bg-s60-7', 'icon-fg': 'icon-fg-s35-7'}


def take(n):
    return Image.open(TAKES / f'{n}.webp').convert('RGB')


def grow(b, m=14):
    return (b[0] - m, b[1] - m, b[2] + m, b[3] + m)


# ───── the kit: (name, sheet, box in the start's layout, the widest it is kept) ─────
BOX = {
    'buttons': [('plankBrown', (40, 40, 960, 220), 600), ('plankGreen', (1080, 40, 2000, 220), 600),
                ('plankGold', (40, 300, 960, 480), 600), ('plankBrownSm', (1080, 300, 1560, 420), 320),
                ('chipOff', (1080, 470, 1400, 570), 220), ('chipOn', (1480, 470, 1800, 570), 220),
                ('plankGreenSm', (1080, 640, 1560, 760), 320), ('plankGoldSm', (40, 820, 520, 940), 320)],
    'panels': [('card', (40, 40, 940, 980), 640), ('textBox', (1000, 26, 2000, 345), 700), ('statTile', (1000, 400, 1300, 620), 220),
               ('lockBadge', (1360, 400, 1560, 600), 140), ('starEmpty', (1600, 400, 1800, 600), 140),
               ('starFull', (1800, 400, 2000, 600), 140), ('sliderTrack', (1000, 690, 1600, 770), 420),
               ('sliderKnob', (1650, 640, 1830, 820), 120)],
}
NAMES = ['play', 'restart', 'map', 'trophy', 'cards', 'book', 'save', 'gear', 'speaker', 'mute', 'cross', 'arrow', 'check', 'lock',
         'star', 'heart', 'medal', 'scroll', 'leaf', 'bulb', 'paw', 'swords', 'expand', 'sloth']
BOX['icons'] = [(f'icon-{n}', (24 + (k % 6) * 340 - 6, 24 + (k // 6) * 340 - 6, 24 + (k % 6) * 340 + 306, 24 + (k // 6) * 340 + 306), 128)
                for k, n in enumerate(NAMES)]
pieces = []
for sheet, rows in BOX.items():
    im = take(PICK[sheet])
    for name, box, mw in rows:
        p = cut(im, 'magenta', grow(box, 6 if sheet == 'icons' else 14), mainOnly=True)
        if p.width > mw:
            p = p.resize((mw, max(1, round(p.height * mw / p.width))), Image.LANCZOS)
        pieces.append((name, p))
W = 2048
x = y = rowh = 0
frames = {}
for name, p in sorted(pieces, key=lambda t: -t[1].height):
    if x + p.width > W:
        x, y, rowh = 0, y + rowh + 4, 0
    frames[name] = {'x': x, 'y': y, 'w': p.width, 'h': p.height}
    x += p.width + 4
    rowh = max(rowh, p.height)
H = y + rowh
atlas = Image.new('RGBA', (W, H), (0, 0, 0, 0))
for name, p in pieces:
    atlas.paste(p, (frames[name]['x'], frames[name]['y']))
(GAME / 'src/assets/ui').mkdir(parents=True, exist_ok=True)
atlas.save(GAME / 'src/assets/ui/ui-kit.webp', 'WEBP', quality=88, method=6)
(GAME / 'src/game/uiKitData.ts').write_text(
    '// generated by tools/art/hfui/uicut.py (2026-10-30): where each painted menu piece sits in src/assets/ui/ui-kit.webp\n'
    '// (Hugging Face img2img takes with the style model, from the game\'s own button colours and icons; the picks are in the script)\n'
    'export interface UiFrame { x: number; y: number; w: number; h: number }\n'
    f'export const UI_KIT_SIZE = {{ w: {W}, h: {H} }};\n'
    'export const UI_KIT: Record<string, UiFrame> = ' + json.dumps(frames, separators=(',', ':')) + ';\n')
print('ui-kit', atlas.size, (GAME / 'src/assets/ui/ui-kit.webp').stat().st_size)
review('kit', [(n, p) for n, p in pieces if not n.startswith('icon-')])
ic = [p for n, p in pieces if n.startswith('icon-')]
grid = Image.new('RGBA', (6 * 132, 4 * 132), (0, 0, 0, 0))
for k, p in enumerate(ic):
    grid.alpha_composite(p, ((k % 6) * 132 + (128 - p.width) // 2, (k // 6) * 132 + (128 - p.height) // 2))
review('icons', [('24 icons (play ... sloth)', grid)], game_h=110)

# ───── the store art ─────
ST = GAME / 'reference/store'
ST.mkdir(parents=True, exist_ok=True)
bg = take(PICK['icon-bg']).resize((1024, 1024), Image.LANCZOS)
# (behind him the forest is softened and darkened a little toward the edges, so he reads first at launcher size)
vig = Image.new('L', (1024, 1024), 0)
ImageDraw.Draw(vig).ellipse((-180, -120, 1204, 1204), fill=255)
vig = vig.filter(ImageFilter.GaussianBlur(160))
bg = Image.composite(bg.filter(ImageFilter.GaussianBlur(3)), Image.eval(bg.filter(ImageFilter.GaussianBlur(3)), lambda v: int(v * 0.72)), vig)
fg = cut(take(PICK['icon-fg']), 'magenta', mainOnly=True)
# (the key left a faint pale rim on his fur: pull the matte in a pixel)
fa = fg.getchannel('A').filter(ImageFilter.MinFilter(3))
fg.putalpha(fa)
# the adaptive foreground: 108 dp with the 66 dp middle always shown, so Pokey's head and shoulders sit in the middle 60%
FG = Image.new('RGBA', (1024, 1024), (0, 0, 0, 0))
s = 600 / max(fg.size)
f2 = fg.resize((round(fg.width * s), round(fg.height * s)), Image.LANCZOS)
FG.alpha_composite(f2, ((1024 - f2.width) // 2, 1024 - 212 - f2.height))
# (his shoulders run to the bottom of the safe circle; below them the layer is clear so the background shows)
FG.resize((432, 432), Image.LANCZOS).save(ST / 'icon-fg-432.png')
bg.resize((432, 432), Image.LANCZOS).save(ST / 'icon-bg-432.png')
# the full icon (store listing and the web app): a bigger Pokey, his shoulders to the bottom edge
full = bg.convert('RGBA')
s = 820 / max(fg.size)
f3 = fg.resize((round(fg.width * s), round(fg.height * s)), Image.LANCZOS)
full.alpha_composite(f3, ((1024 - f3.width) // 2, 1024 - f3.height))
full = full.convert('RGB')
full.resize((512, 512), Image.LANCZOS).save(ST / 'icon-512.png')
PUB = GAME / 'public'
full.resize((512, 512), Image.LANCZOS).save(PUB / 'pwa-512x512.png')
full.resize((192, 192), Image.LANCZOS).save(PUB / 'pwa-192x192.png')
full.resize((180, 180), Image.LANCZOS).save(PUB / 'apple-touch-icon.png')
# the maskable web icon: the adaptive layers flattened (the head inside the middle 80% safe circle)
mk = bg.convert('RGBA')
mk.alpha_composite(FG)
mk.convert('RGB').resize((512, 512), Image.LANCZOS).save(PUB / 'pwa-maskable-512x512.png')
# the feature graphic and the splash: the title scene itself (its painted canopy, the carved logo, Pokey and Meeca on the log)
Image.open(FEATURE).convert('RGB').resize((1024, 500), Image.LANCZOS).save(ST / 'feature-1024x500.png')
Image.open(SQUARE).convert('RGB').resize((2732, 2732), Image.LANCZOS).save(ST / 'splash-2732.jpg', quality=90)
# a look at the icon as a launcher shows it: masked to a circle and a rounded square, at 48 and 96 px, on dark and light
L = Image.new('RGB', (900, 300), (30, 30, 30))
d = ImageDraw.Draw(L)
L.paste((235, 235, 235), (450, 0, 900, 300))
x0 = 20
for bgc in (0, 1):
    for sz in (96, 48):
        for shape in ('circle', 'squircle'):
            m = Image.new('L', (sz, sz), 0)
            if shape == 'circle':
                ImageDraw.Draw(m).ellipse((0, 0, sz - 1, sz - 1), fill=255)
            else:
                ImageDraw.Draw(m).rounded_rectangle((0, 0, sz - 1, sz - 1), sz // 4, fill=255)
            src = mk.convert('RGB').resize((sz, sz), Image.LANCZOS)
            L.paste(src, (x0, 100 if sz == 96 else 124), m)
            x0 += sz + 14
    x0 = 470
L.save(bosscut_lib.QA / 'review-launcher.jpg', quality=90)
print('store art in', ST)
