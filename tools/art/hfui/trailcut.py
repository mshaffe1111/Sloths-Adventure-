"""Cut the ten world-map trails (hftrails1) into src/assets/ui/trails.webp + src/game/trailsData.ts: four pieces per world, each keyed
off magenta and kept at most 128 px wide (they are drawn about 40-56 px long on the map, so 2x at most), and a review sheet.
    python3 -I tools/art/hfui/trailcut.py <takes dir> <game checkout> <pick for worlds 1-5> <pick for worlds 6-10>
"""
import json, sys
from pathlib import Path
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'hfbosses'))
TAKES, GAME, PA, PB = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3], sys.argv[4]
sys.argv = [sys.argv[0], str(TAKES), str(GAME)]
import bosscut_lib  # noqa: E402
bosscut_lib.QA = GAME / 'reference/prop-sheets/qa-notes/hf-ui'
from bosscut_lib import cut, review  # noqa: E402

pieces = []
for sheet, worlds in ((PA, range(1, 6)), (PB, range(6, 11))):
    im = Image.open(TAKES / f'{sheet}.webp').convert('RGB')
    for row, w in enumerate(worlds):
        for k in range(4):
            x, y = 32 + k * 500, 12 + row * 202
            p = cut(im, 'magenta', (x - 14, y, x + 494, y + 202), crumbs=150)
            if p.width > 128:
                p = p.resize((128, max(1, round(p.height * 128 / p.width))), Image.LANCZOS)
            pieces.append((f'w{w}-{k}', p))
W = 1024
x = y = rowh = 0
frames = {}
for name, p in pieces:  # in world order, so a world's four sit together
    if x + p.width > W:
        x, y, rowh = 0, y + rowh + 4, 0
    frames[name] = {'x': x, 'y': y, 'w': p.width, 'h': p.height}
    x += p.width + 4
    rowh = max(rowh, p.height)
atlas = Image.new('RGBA', (W, y + rowh), (0, 0, 0, 0))
for name, p in pieces:
    atlas.paste(p, (frames[name]['x'], frames[name]['y']))
atlas.save(GAME / 'src/assets/ui/trails.webp', 'WEBP', quality=88, method=6)
by_world = {w: [frames[f'w{w}-{k}'] for k in range(4)] for w in range(1, 11)}
(GAME / 'src/game/trailsData.ts').write_text(
    '// generated by tools/art/hfui/trailcut.py (2026-10-30): each world map\'s four painted trail pieces in src/assets/ui/trails.webp\n'
    '// (Hugging Face img2img takes with the style model; vine rope, stepping stones, glowworm roots, clouds, orchid stems, boardwalk,\n'
    '// temple steps, moonlit roots, cooled lava, iron chain). Each piece runs left to right, the way the trail goes.\n'
    'export interface TrailFrame { x: number; y: number; w: number; h: number }\n'
    f'export const TRAILS_SIZE = {{ w: {W}, h: {atlas.height} }};\n'
    'export const TRAILS: Record<number, TrailFrame[]> = ' + json.dumps(by_world, separators=(',', ':')) + ';\n')
print('trails', atlas.size, (GAME / 'src/assets/ui/trails.webp').stat().st_size)
grid = Image.new('RGBA', (4 * 136, 10 * 80), (0, 0, 0, 0))
for name, p in pieces:
    w, k = int(name[1:].split('-')[0]), int(name.split('-')[1])
    grid.alpha_composite(p, (k * 136 + (128 - p.width) // 2, (w - 1) * 80 + max(0, (76 - p.height) // 2)))
review('trails', [('the ten world trails, four pieces each (worlds 1-10 top to bottom)', grid)], game_h=400)
