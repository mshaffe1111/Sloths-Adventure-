"""Bring a set of repainted story figures into the game: cut each pick off its grey (cut.py), pack the set's pages (pack.py) into
src/assets/story/hd/<set>-<n>.webp and write src/game/storyHdData_<set>.ts (rects in the new pages; the old anchors stay valid, times HD).

    python3 -I tools/art/storyart/wire_figures.py <set> <dir of repainted PNG/WebP> [picks.json]

<dir> holds <set>-<frame>-<tag>.<ext> takes (unpacked carriers); picks.json {frame: tag} chooses among takes (default: the only or first).
The set's meta (starts.py figures) says where each start put the old frame. Writes a review sheet of every frame, old next to new, on dark.
"""
import json, re, sys
from pathlib import Path
from PIL import Image, ImageDraw

sys.path.insert(0, str(Path(__file__).resolve().parent))
from cut import cut_figure, on_dark  # noqa: E402
from pack import pack  # noqa: E402

REPO = Path(__file__).resolve().parents[3]
SETS = {'pokey': 2.0, 'meeca': 2.0, 'dot': 3.0}


def main():
    which, src = sys.argv[1], Path(sys.argv[2])
    hd = SETS[which]
    picks = json.loads(Path(sys.argv[3]).read_text()) if len(sys.argv) > 3 else {}
    meta = json.loads((REPO / f'tools/art/hfbatch/starts/storyart/meta-{which}.json').read_text())
    takes = {}
    for p in sorted(src.iterdir()):
        m = re.match(rf'{which}-(.+?)-(s\d+.*)\.(png|webp)$', p.name)
        if m:
            takes.setdefault(m.group(1), {})[m.group(2)] = p
    figs, olds = {}, {}
    missing = []
    for key, m in meta.items():
        name = key[len(which) + 1:]
        t = takes.get(name)
        if not t:
            missing.append(name)
            continue
        tag = picks.get(name) or sorted(t)[0]
        atlas, x, y, w, h = m['src']
        old = Image.open(REPO / atlas).convert('RGBA').crop((x, y, x + w, y + h))
        im, mg = cut_figure(Image.open(t[tag]), m, old, hd, rect_margin=6)
        figs[name] = im
        olds[name] = (old, mg)
    pages, places = pack(figs, max_w=2048, max_h=2048)
    out = REPO / 'src/assets/story/hd'
    out.mkdir(parents=True, exist_ok=True)
    for f in out.glob(f'{which}-*.webp'):
        f.unlink()
    sizes = []
    for i, pg in enumerate(pages):
        pg.save(out / f'{which}-{i}.webp', 'WEBP', quality=90, method=6)
        sizes.append((pg.width, pg.height, (out / f'{which}-{i}.webp').stat().st_size))
    rows = ',\n'.join(f"  {json.dumps(n)}: {{ p: {p}, x: {x}, y: {y}, w: {w}, h: {h}, m: {round(olds[n][1], 2)} }}" for n, (p, x, y, w, h) in sorted(places.items()))
    ts = (f"/** Generated by tools/art/storyart/wire_figures.py: {which}'s story frames repainted on Hugging Face at {hd}x (storyHd.ts). Each frame is its old\n"
          f" * rect times HD, grown by m px all round; the old anchors (feet, head) times HD, plus m, are its anchors here. Do not edit by hand. */\n"
          f"export const HD_{which.upper()} = {hd};\nexport const HD_{which.upper()}_PAGES = {len(pages)};\n"
          f"export const HD_{which.upper()}_FRAMES: Record<string, {{ p: number; x: number; y: number; w: number; h: number; m: number }}> = {{\n{rows},\n}};\n")
    (REPO / f'src/game/storyHdData_{which}.ts').write_text(ts)
    print(which, len(figs), 'frames,', 'pages', sizes, 'missing', missing)
    # review: old (scaled up) and new, side by side on dark, 6 to a row
    cells = []
    for n in sorted(figs):
        old, _ = olds[n]
        o = on_dark(old.resize((round(old.width * hd), round(old.height * hd)), Image.LANCZOS))
        nw = on_dark(figs[n])
        c = Image.new('RGB', (o.width + nw.width + 12, max(o.height, nw.height) + 18), (24, 28, 32))
        c.paste(o, (0, 18)); c.paste(nw, (o.width + 12, 18))
        ImageDraw.Draw(c).text((4, 2), n, fill=(255, 230, 0))
        c.thumbnail((520, 420))
        cells.append(c)
    qa = REPO / 'reference/prop-sheets/qa-notes/story-art'
    qa.mkdir(parents=True, exist_ok=True)
    for s in range(0, len(cells), 12):
        part = cells[s:s + 12]
        S = Image.new('RGB', (4 * 520, 3 * 420), (24, 28, 32))
        for i, c in enumerate(part):
            S.paste(c, ((i % 4) * 520, (i // 4) * 420))
        S.save(qa / f'{which}-old-new-{s // 12}.jpg', quality=84)


if __name__ == '__main__':
    main()
