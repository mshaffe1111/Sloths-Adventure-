"""Bring the repainted story-sheet cels into the game: cut each pick (cut.py), pack the pages (pack.py) into
src/assets/characters/cels-<n>.webp and rewrite src/game/storyCelData.ts. A cel is its old rect (in the old atlas) times CEL_HD, grown by
`m` px all round (storyCels.ts drawCel takes the margin off again), so every pose keeps its feet where they were.

    python3 -I tools/art/storyart/wire_cels.py <picks.json> <dir> [<dir> ...]
picks.json {cel key: take name (file stem)}; the dirs hold the unpacked takes. Takes named gen-* are the General's (edit model, cut by the
key alone: his coat and cape go past the old outline). gn.card_* are his three story-card poses, cut from the boss atlas rects.
"""
import json, re, sys
from pathlib import Path
from PIL import Image, ImageDraw

sys.path.insert(0, str(Path(__file__).resolve().parent))
from cut import cut_figure, on_dark  # noqa: E402
from pack import pack  # noqa: E402

REPO = Path(__file__).resolve().parents[3]
HD = 2.0
ST = REPO / 'tools/art/hfbatch/starts/storyart'


def main():
    picks = json.loads(Path(sys.argv[1]).read_text())
    files = {}
    for d in sys.argv[2:]:
        for p in Path(d).iterdir():
            files[p.stem] = p
    meta = json.loads((ST / 'meta-cel.json').read_text())
    r2 = json.loads((ST / 'meta-r2.json').read_text())
    figs, info = {}, {}
    for key, take in picks.items():
        p = files[take]
        gen = Image.open(p)
        general = take.startswith('gen-')
        if key.startswith('gn.card_'):
            n = key[8:]
            m = dict(r2[f'r2-gen-{n}'])
            src = (REPO / 'src/game/ironclawAtlasData.ts').read_text()
            i = src.index('= {', src.index('IRONCLAW_FRAMES')) + 2
            r = json.JSONDecoder().raw_decode(src[i:])[0][n]
            old = Image.open(REPO / 'src/assets/enemies/ironclaw-atlas.webp').convert('RGBA').crop((r['x'], r['y'], r['x'] + r['w'], r['y'] + r['h']))
            face, raw, cut_c = 1, False, None
        elif key in ('mc.grip_wall', 'mc.reach_back'):
            # (new pictures, made from his from-behind frame of the story poses: the same size and feet as that frame)
            m = json.loads((ST / 'meta-pokey.json').read_text())['pokey-away']
            atlas, x, y, w, h = m['src']
            old = Image.open(REPO / atlas).convert('RGBA').crop((x, y, x + w, y + h))
            face, raw, cut_c = 0, False, None
            general = True
        else:
            m = meta[f'cel-{key}']
            atlas, x, y, w, h = m['src']
            old = Image.open(REPO / atlas).convert('RGBA').crop((x, y, x + w, y + h))
            face, raw, cut_c = m['cel']['f'], m['cel'].get('c') == 'raw', m['cel'].get('c')
        # (the edit model's start was 1024 square too; its picture is the same size, so the start's mapping holds for it)
        if gen.size != tuple(m.get('size', (1024, 1024))):
            gen = gen.resize(tuple(m.get('size', (1024, 1024))), Image.LANCZOS)
        if raw:
            s, ox, oy = m['scale'], m['ox'], m['oy']
            im = gen.convert('RGBA').crop((ox, oy, round(ox + old.width * s), round(oy + old.height * s))).resize((round(old.width * HD), round(old.height * HD)), Image.LANCZOS)
            mg = 0
        else:
            im, mg = cut_figure(gen, m, old, HD, rect_margin=30 if general else 6, limit=not general)
        figs[key] = im
        info[key] = (face, cut_c, mg, old)
    pages, places = pack(figs, max_w=2048, max_h=2048)
    out = REPO / 'src/assets/characters'
    for f in out.glob('cels-*.webp'):
        f.unlink()
    for i, pg in enumerate(pages):
        pg.save(out / f'cels-{i}.webp', 'WEBP', quality=90, method=6)
    rows = []
    for k in sorted(places):
        p, x, y, w, h = places[k]
        face, c, mg, _ = info[k]
        extra = f", c: '{c}'" if c else ''
        rows.append(f"  '{k}': {{ a: {p}, x: {x}, y: {y}, w: {w}, h: {h}, f: {face}, m: {round(mg, 2)}{extra} }},")
    sizes = ', '.join(f'{{ w: {pg.width}, h: {pg.height} }}' for pg in pages)
    ts = ('/** Generated by tools/art/storyart/wire_cels.py: the story-sheet cast repainted on Hugging Face (2026-10-29) at CEL_HD times the old\n'
          ' * sheets\' size. A frame is its old rect times CEL_HD grown by `m` px all round (drawCel takes the margin off, so the feet stay put). */\n'
          'export interface CelFrame {\n  /** which page (src/assets/characters/cels-<a>.webp) */\n  a: number;\n  x: number; y: number; w: number; h: number;\n'
          '  /** the way the figure looks in the sheet: -1 left, 1 right, 0 front or unclear (never flipped for facing) */\n  f: -1 | 0 | 1;\n'
          '  /** the margin grown round the old rect, px */\n  m: number;\n'
          '  /** b: cut off at the bottom (drawn with a soft fade); raw: an opaque picture, not a cut-out */\n  c?: \'b\' | \'raw\';\n}\n'
          f'/** atlas px per px of the old sheets (CEL_K is in old px) */\nexport const CEL_HD = {HD};\n'
          f'export const CEL_ATLAS_SIZES = [{sizes}] as const;\n'
          'export const CELS: Record<string, CelFrame> = {\n' + '\n'.join(rows) + '\n};\n')
    (REPO / 'src/game/storyCelData.ts').write_text(ts)
    print(len(figs), 'cels', [(pg.width, pg.height, (out / f'cels-{i}.webp').stat().st_size) for i, pg in enumerate(pages)])
    cells = []
    for k in sorted(figs):
        old = info[k][3]
        o = on_dark(old.resize((round(old.width * HD), round(old.height * HD)), Image.LANCZOS))
        nw = on_dark(figs[k])
        c = Image.new('RGB', (o.width + nw.width + 12, max(o.height, nw.height) + 18), (24, 28, 32))
        c.paste(o, (0, 18)); c.paste(nw, (o.width + 12, 18))
        ImageDraw.Draw(c).text((4, 2), k, fill=(255, 230, 0))
        c.thumbnail((520, 420))
        cells.append(c)
    qa = REPO / 'reference/prop-sheets/qa-notes/story-art'
    qa.mkdir(parents=True, exist_ok=True)
    for s in range(0, len(cells), 12):
        S = Image.new('RGB', (4 * 520, 3 * 420), (24, 28, 32))
        for i, c in enumerate(cells[s:s + 12]):
            S.paste(c, ((i % 4) * 520, (i // 4) * 420))
        S.save(qa / f'cels-old-new-{s // 12}.jpg', quality=84)


if __name__ == '__main__':
    main()
