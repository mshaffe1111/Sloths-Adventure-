"""Pack a trained World 5 creature's pose stills (its model's samples on plain grey) into the game's creature atlas format:
src/assets/enemies/<name>-poses.webp + src/game/<name>AtlasData.ts with <NAME>_FRAMES {x, y, w, h, ax, ay} and <NAME>_ATLAS_SIZE, like the
spider's and the other painted creatures'. Not used by any stage yet.

    python3 -I tools/art/w5/pack_poses.py <name> <ground|air> <idle height px> '<json {pose: picture path}>'
    (a path ending in |flip is mirrored first: the stills that face left)

Each picture is keyed off its own background (a smooth quadratic fitted to its border, w5lib.sheet_mask) and cut to the creature;
`idle` is scaled to the given height and every other pose to the same painted area (the model draws each still at its own size).
The anchor: for a ground creature the middle of its lowest solid row (feet on the ground line); for a flyer or a hanger the middle of
its body (it hangs at its hit box).
"""
import json, os, sys
from pathlib import Path
import numpy as np
from PIL import Image
from scipy import ndimage
sys.path.insert(0, str(Path(__file__).resolve().parent))
from w5lib import sheet_mask  # noqa: E402

name, kind, idle_h = sys.argv[1], sys.argv[2], int(sys.argv[3])
poses = json.loads(sys.argv[4])
G = Path(os.environ.get('OUTDIR', str(Path(__file__).resolve().parents[3])))


def cut(path):
    flip = path.endswith('|flip')  # a still that came out facing left: mirrored, since the game's frames face right
    path = path.split('|')[0]
    im = Image.open(path).convert('RGB')
    if flip:
        im = im.transpose(Image.FLIP_LEFT_RIGHT)
    a = np.asarray(im).astype(np.float32)
    d = sheet_mask(a)
    fig = ndimage.binary_opening(d > 30, iterations=1)
    lab, n = ndimage.label(ndimage.binary_dilation(fig, iterations=6))
    sizes = ndimage.sum(fig, lab, range(1, n + 1))
    keep = np.isin(lab, 1 + np.flatnonzero(sizes > sizes.max() * 0.03)) & fig
    keep = ndimage.binary_fill_holes(keep) | keep
    alpha = np.clip((d - 18) / 26, 0, 1) * ndimage.binary_dilation(keep, iterations=2)
    ys, xs = np.nonzero(alpha > 0.5)
    x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
    rgba = np.dstack([a[y0:y1, x0:x1], alpha[y0:y1, x0:x1] * 255]).astype(np.uint8)
    return Image.fromarray(rgba, 'RGBA')


pics = {p: cut(f) for p, f in poses.items()}
# each still came out at its own size, so every pose is scaled to the same picture area as `idle` at the given height (a pose that
# stretches out keeps its shape but not a bigger body)
area = lambda im: float((np.asarray(im.getchannel('A')) > 128).sum())
ref = pics['idle'] if 'idle' in pics else max(pics.values(), key=lambda q: q.height)
target = area(ref) * (idle_h / ref.height) ** 2
frames = {}
for p, im in pics.items():
    k = (target / max(1.0, area(im))) ** 0.5
    im = im.resize((max(1, round(im.width * k)), max(1, round(im.height * k))), Image.LANCZOS)
    al = np.asarray(im.getchannel('A')) > 128
    if kind == 'ground':
        ys = np.nonzero(al.any(1))[0]
        low = ys.max()
        cols = np.nonzero(al[max(0, low - 6):low + 1].any(0))[0]
        ax, ay = float((cols.min() + cols.max()) / 2), float(low + 1)
    else:
        ax, ay = im.width / 2, im.height / 2
    frames[p] = (im, round(ax, 1), round(ay, 1))
Wd, pad = 2048, 2
x = y = rowh = 0
pos = {}
for p in sorted(frames, key=lambda q: -frames[q][0].height):
    im = frames[p][0]
    if x + im.width + pad > Wd:
        x = 0; y += rowh + pad; rowh = 0
    pos[p] = (x, y); x += im.width + pad; rowh = max(rowh, im.height)
W2 = min(Wd, max(pos[p][0] + frames[p][0].width for p in pos))
sheet = Image.new('RGBA', (W2, y + rowh), (0, 0, 0, 0))
for p, xy in pos.items():
    sheet.paste(frames[p][0], xy)
(G / 'src/assets/enemies').mkdir(parents=True, exist_ok=True)
(G / 'src/game').mkdir(parents=True, exist_ok=True)
out = G / f'src/assets/enemies/{name}-poses.webp'  # not -atlas: creatureArt.ts bundles every *-atlas.webp
sheet.save(out, 'WEBP', quality=82, method=6)
data = {p: {'x': pos[p][0], 'y': pos[p][1], 'w': frames[p][0].width, 'h': frames[p][0].height, 'ax': frames[p][1], 'ay': frames[p][2]} for p in poses}
C, T = name.upper(), name[0].upper() + name[1:]
where = 'the middle of the feet on the ground line' if kind == 'ground' else 'the middle of the body'
ts = (f'/** Generated by tools/art/w5/pack_poses.py from the {name} model\'s pose stills (mshaffe111/{name}-qwen-lora, World 5, 2026-10-26). '
      f'Frames face RIGHT;\n * ax/ay is {where}. Not used by any stage yet. */\n')
ts += f'export interface {T}Frame {{ x: number; y: number; w: number; h: number; ax: number; ay: number }}\n'
ts += f"export const {C}_ATLAS_URL = new URL('../assets/enemies/{name}-poses.webp', import.meta.url).href;\n"
ts += f'export const {C}_ATLAS_SIZE = {{ w: {sheet.width}, h: {sheet.height} }};\n'
ts += f'export const {C}_FRAMES: Record<string, {T}Frame> = ' + json.dumps(data) + ';\n'
(G / f'src/game/{name}AtlasData.ts').write_text(ts)
print(name, sheet.size, round(out.stat().st_size / 1024), 'KB', {p: frames[p][0].size for p in frames})
