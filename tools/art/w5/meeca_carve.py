"""Meeca's "carving on the trunk" frames for her World 5 bonus stage (2026-10-26): from the clip packed by w5cpu.py packall (meeca, UP 1, so
the frames are meeca-standard.webp's size), with the tree trunk she carves cut away so the game's own trunk can stand there.
Writes src/assets/characters/meeca-carve.webp + src/game/meecaCarveData.ts. Not used by any stage yet.

    python3 -I tools/art/w5/meeca_carve.py <meeca-pick-anim.webp> <meeca-pickAnimData.ts> '<json [frame numbers]>'

The trunk stands still in the clip: its face is fitted once (the left edge of the bark on the first frame, where background meets it) and
everything right of it is cut from every frame; the anchor is unchanged (the middle of her feet on the ground line), and `touch` is how far right of the
anchor the trunk's face was, in atlas px, so a stage can stand her that far from its trunk.
"""
import json, re, sys
from pathlib import Path
import numpy as np
from PIL import Image
from scipy import ndimage

sheet = Image.open(sys.argv[1]).convert('RGBA')
src = Path(sys.argv[2]).read_text()
pick = json.loads(sys.argv[3])
fr = json.loads(re.search(r'_ANIM: Record<string, AnimFrame> = (\{.*\});', src).group(1))
G = Path(__file__).resolve().parents[3]
out = {}
# the trunk stands still in the clip, so its face is one line in anchor coordinates: fitted on the first frame's rows where open
# background meets it (not where her paws touch it) as the left edge of the bark joined to the frame's right side; everything right of it goes in every frame
f0 = fr[f'carve_{pick[0]:02d}']
im0 = np.asarray(sheet.crop((f0['x'], f0['y'], f0['x'] + f0['w'], f0['y'] + f0['h']))).astype(np.int16)
rgb0 = im0[..., :3]
bark0 = (im0[..., 3] > 128) & (((rgb0[..., 0] > rgb0[..., 1] + 12) & (rgb0.sum(-1) < 330)) | (rgb0.sum(-1) < 200))  # bark, its grain lines and outline
pts = []
for yy in range(int(f0['h'] * 0.02), int(f0['h'] * 0.97)):
    xs = np.nonzero(bark0[yy])[0]
    if len(xs) and xs.max() >= f0['w'] - 3:
        # the run of bark that reaches the right edge
        run = xs[-1]
        for x_ in xs[::-1]:
            if run - x_ > 1:
                break
            run = x_
        if run > 3 and im0[yy, run - 3, 3] < 60:  # only rows where open background meets the trunk (not her paw)
            pts.append((yy - f0['ay'], run - f0['ax']))
P = np.array(pts, float)
slope, icept = np.polyfit(P[:, 0], P[:, 1], 1)
face = lambda yrel: slope * yrel + icept  # x of the trunk's face, anchor coordinates
touches = [icept]
for i in pick:
    n = f'carve_{i:02d}'
    f = fr[n]
    im = np.asarray(sheet.crop((f['x'], f['y'], f['x'] + f['w'], f['y'] + f['h']))).astype(np.int16).copy()
    a = im[..., 3]
    yy, xx = np.mgrid[0:f['h'], 0:f['w']]
    d = (xx - f['ax']) - face(yy - f['ay'])
    cut = (d > 1) | ((d > -4) & (im[..., :3].sum(-1) < 200))  # past the face, and the trunk's dark outline just before it
    a = np.where(cut, 0, a)
    lab, k = ndimage.label(a > 16)
    if k > 1:  # crumbs of bark left at the cut
        sizes = ndimage.sum(np.ones_like(lab), lab, range(1, k + 1))
        a = np.where(np.isin(lab, 1 + np.flatnonzero(sizes >= sizes.max() * 0.02)), a, 0)
    im[..., 3] = a
    ys, xs2 = np.nonzero(a > 16)
    x0, x1, y0, y1 = xs2.min(), xs2.max() + 1, ys.min(), ys.max() + 1
    piece = Image.fromarray(im[y0:y1, x0:x1].astype(np.uint8), 'RGBA')
    out[n] = (piece, f['ax'] - x0, f['ay'] - y0)
Wd, pad = 1024, 2
x = y = rowh = 0
pos = {}
for n in out:
    im = out[n][0]
    if x + im.width + pad > Wd:
        x = 0; y += rowh + pad; rowh = 0
    pos[n] = (x, y); x += im.width + pad; rowh = max(rowh, im.height)
W2 = max(pos[n][0] + out[n][0].width for n in pos)
S = Image.new('RGBA', (W2, y + rowh), (0, 0, 0, 0))
for n, p in pos.items():
    S.paste(out[n][0], p)
dst = G / 'src/assets/characters/meeca-carve.webp'
S.save(dst, 'WEBP', quality=85, method=6)
data = {n: {'x': pos[n][0], 'y': pos[n][1], 'w': out[n][0].width, 'h': out[n][0].height, 'ax': round(out[n][1], 1), 'ay': round(out[n][2], 1)} for n in out}
touch = round(float(np.median(touches)), 1) if touches else 0
ts = ("/** Generated by tools/art/w5/meeca_carve.py: Meeca carving a warning into a trunk with her hairpin (World 5 bonus stage, 2026-10-26), from a\n"
      " * Wan 2.2 clip of an on-model edit of her own frames (the takes with her model drifted off-model), with the clip's trunk cut away. Same pixel size as meeca-standard.webp (draw at its\n"
      " * scale); ax/ay is the middle of her feet on the ground line; she faces RIGHT, the trunk's face is MEECA_CARVE_TOUCH px right of the\n"
      " * anchor. Plays at 16 frames a second, looping. Not used by any stage yet. */\n")
ts += "export interface MeecaCarveFrame { x: number; y: number; w: number; h: number; ax: number; ay: number }\n"
ts += "export const MEECA_CARVE_URL = new URL('../assets/characters/meeca-carve.webp', import.meta.url).href;\n"
ts += f'export const MEECA_CARVE_SIZE = {{ w: {S.width}, h: {S.height} }};\n'
ts += 'export const MEECA_CARVE_FPS = 16;\n'
ts += f'export const MEECA_CARVE_TOUCH = {touch};\n'
ts += 'export const MEECA_CARVE_SEQ: readonly string[] = ' + json.dumps(list(out)) + ';\n'
ts += 'export const MEECA_CARVE_FRAMES: Record<string, MeecaCarveFrame> = ' + json.dumps(data) + ';\n'
(G / 'src/game/meecaCarveData.ts').write_text(ts)
print(S.size, round(dst.stat().st_size / 1024), 'KB', len(out), 'frames, touch', touch)
