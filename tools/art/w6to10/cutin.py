"""Place the cut Worlds 5-10 sheets (cutpack.py's output, unpacked from the bucket's w6to10/cutin/carrier-*.png) into a game checkout.

    python3 -I tools/art/w6to10/cutin.py <unpacked dir> <game checkout>

In the game now (src/assets + a data file each, the format of tools/art/reanim/pack.py, read by creatureAnim.ts makeCreatureAnim):
  the four World 5 creatures   src/assets/enemies/<c>-anim.webp + src/game/<c>AnimData.ts
  Flicker                      src/assets/characters/flicker-anim.webp + src/game/flickerAnimData.ts
  the water signs              src/assets/props/water-signs.webp + src/game/waterSignData.ts
  the far strips (W6-W10)      src/assets/backdrops/w<N><time>-far.webp (stageBackdrops.ts FAR_BY_STAGE names them)
Ready, not drawn yet (assets + src/assets/w6to10/manifest.json, which nothing imports, so the bundle is unchanged):
  the guardians' clips         src/assets/w6to10/bosses/<boss>-anim[-k].webp + <boss>.json
  lairs, moving lairs          src/assets/w6to10/lairs/lair-<boss>-<calm|rage>.webp, plate-<boss>.webp + lairplates.json
  collar, collars off, props   src/assets/w6to10/{collar,guardiansfree,props}.webp + .json
"""
import json, shutil, sys
from pathlib import Path
from PIL import Image

SRC, GAME = Path(sys.argv[1]), Path(sys.argv[2])
A = GAME / 'src/assets'
G = GAME / 'src/game'
W = A / 'w6to10'
INGAME = {'dangler': 'enemies', 'seamstress': 'enemies', 'mantis': 'enemies', 'dozer': 'enemies', 'flicker': 'characters'}
BOSSES = ['ironclaw', 'golem', 'drake', 'reaver', 'thornbark', 'monarch']
manifest = {'note': 'Worlds 5-10 art cut in 2026-10-29 (tools/art/w6to10/cutpack.py + cutin.py), ready for the boss fights and the worlds '
                    'still being built; nothing imports these yet. Clip sheets: frames keyed off the grey, every 2nd Wan frame (8 fps); '
                    'anchors are the old painted frames\' (draw at the sprite\'s K / up), see each json.', 'bosses': {}, 'files': {}}


def size(p):
    return p.stat().st_size


MAX_H = 7000


def merge(j, out):
    """one picture for a clip set cut onto several sheets: every frame cropped, scaled so the lot fits MAX_H tall, shelf-packed again"""
    sheets = [Image.open(SRC / s['file']).convert('RGBA') for s in j['sheets']]
    total = sum(s['h'] for s in j['sheets'])
    k = min(1.0, MAX_H / total)
    while True:
        cells, x, y, row = {}, 0, 0, 0
        for n, f in j['frames'].items():
            w, h = max(1, round(f['w'] * k)), max(1, round(f['h'] * k))
            if x + w > 2048:
                x, y, row = 0, y + row + 2, 0
            cells[n] = (x, y, w, h)
            x, row = x + w + 2, max(row, h)
        if y + row <= MAX_H:
            break
        k *= 0.97
    pic = Image.new('RGBA', (2048, y + row))
    frames = {}
    for n, f in j['frames'].items():
        x, y, w, h = cells[n]
        im = sheets[f['s']].crop((f['x'], f['y'], f['x'] + f['w'], f['y'] + f['h'])).resize((w, h), Image.LANCZOS)
        pic.paste(im, (x, y))
        frames[n] = {'s': 0, 'x': x, 'y': y, 'w': w, 'h': h, 'ax': round(f['ax'] * k, 1), 'ay': round(f['ay'] * k, 1)}
    pic.save(out, 'WEBP', quality=88, method=6)
    j = dict(j, frames=frames, sheets=[{'file': out.name, 'w': 2048, 'h': pic.height}], up=round(j['up'] * k, 4),
             target=round(j['target'] * k) if j.get('target') else j.get('target'))
    print('  merged', len(sheets), 'sheets at', round(k, 3), '->', pic.size)
    return j


def clip_ts(name, j, folder):
    cap = name.upper()
    frames = {n: {k: f[k] for k in ('x', 'y', 'w', 'h', 'ax', 'ay')} for n, f in j['frames'].items()}
    up = j['up'] if j['anchor'] == 'meta' else 1
    head = (f"/** Generated by tools/art/w6to10/cutin.py from Wan 2.2 clips (motion model) of the {name}'s own painted poses (picked takes: "
            f"{', '.join(f'{k} {v}' for k, v in j['source'].items())}), 2026-10-29. Frames face RIGHT, every 2nd clip frame ({j['fps']} fps). ")
    if j['anchor'] == 'meta':
        head += f"ax/ay carry the old painted frame's anchor, {up} times its size (draw at the old K / ANIM_UP). */\n"
    else:
        head += f"ax/ay is the middle of the figure in each clip's first frame, which is {j['target']} sheet px tall. */\n"
    ts = head + "import type { AnimFrame } from './creatureAnim.ts';\n"
    ts += f'export const {cap}_ANIM_UP = {up};\n'
    ts += f"export const {cap}_ANIM_URL = new URL('../assets/{folder}/{name}-anim.webp', import.meta.url).href;\n"
    if j.get('target'):
        ts += f'/** the height of each sequence\'s first frame, sheet px */\nexport const {cap}_ANIM_H = {j["target"]};\n'
    sh = j['sheets'][0]
    ts += f"export const {cap}_ANIM_SIZE = {{ w: {sh['w']}, h: {sh['h']} }};\n"
    ts += f'export const {cap}_ANIM_FPS = {j["fps"]};\n'
    ts += f'export const {cap}_SEQ: Record<string, readonly string[]> = ' + json.dumps(j['seq']) + ';\n'
    ts += f'export const {cap}_ANIM: Record<string, AnimFrame> = ' + json.dumps(frames) + ';\n'
    (G / f'{name}AnimData.ts').write_text(ts)


for name, folder in INGAME.items():
    jp = SRC / f'{name}.json'
    if not jp.exists():
        print('missing', name); continue
    j = json.loads(jp.read_text())
    dst = A / folder / f'{name}-anim.webp'
    if len(j['sheets']) > 1:
        j = merge(j, dst)
    else:
        shutil.copy(SRC / j['sheets'][0]['file'], dst)
    clip_ts(name, j, folder)
    print(name, dst, size(dst))

# the water signs: two takes each, anchored at the middle of the post's foot
jp = SRC / 'watersigns.json'
if jp.exists():
    j = json.loads(jp.read_text())['_atlas']
    shutil.copy(SRC / j['sheets'][0], A / 'props/water-signs.webp')
    fr = {n: {k: f[k] for k in ('x', 'y', 'w', 'h', 'ax', 'ay')} for n, f in j['frames'].items()}
    (G / 'waterSignData.ts').write_text(
        "/** Generated by tools/art/w6to10/cutin.py: the water's-edge warning signs (style model, 2026-10-28; no words, a wave on the board):\n"
        " * sign-w5 the World 5 garden look (silver wood, silk, an orchid), sign-jungle Worlds 6-10 (brown wood and vine); -b the second take.\n"
        " * ax/ay: the middle of the post's foot. */\n"
        "export interface SignFrame { x: number; y: number; w: number; h: number; ax: number; ay: number }\n"
        "export const WATER_SIGN_URL = new URL('../assets/props/water-signs.webp', import.meta.url).href;\n"
        f"export const WATER_SIGN_SIZE = {{ w: {Image.open(A / 'props/water-signs.webp').width}, h: {Image.open(A / 'props/water-signs.webp').height} }};\n"
        "export const WATER_SIGN_FRAMES: Record<string, SignFrame> = " + json.dumps(fr) + ';\n')
    print('signs', size(A / 'props/water-signs.webp'))

jp = SRC / 'farstrips.json'
if jp.exists():
    for n, f in json.loads(jp.read_text()).items():
        shutil.copy(SRC / f['file'], A / 'backdrops' / f['file'])
        print('far', f['file'], size(A / 'backdrops' / f['file']))

# ready, not drawn
for sub in ('bosses', 'lairs', 'props'):
    (W / sub).mkdir(parents=True, exist_ok=True)
for b in BOSSES:
    jp = SRC / f'{b}.json'
    if not jp.exists():
        print('missing', b); continue
    j = json.loads(jp.read_text())
    for s in j['sheets']:
        shutil.copy(SRC / s['file'], W / 'bosses' / s['file'])
        manifest['files'][f'bosses/{s["file"]}'] = size(W / 'bosses' / s['file'])
    shutil.copy(jp, W / 'bosses' / f'{b}.json')
    manifest['bosses'][b] = {'sheets': [s['file'] for s in j['sheets']], 'moves': {k: len(v) for k, v in j['seq'].items()},
                             'up': j['up'], 'source': j['source'], 'data': f'bosses/{b}.json'}
for grp, sub in (('lairs', 'lairs'), ('lairplates', 'lairs'), ('collar', 'props'), ('guardiansfree', 'props'), ('props', 'props')):
    jp = SRC / f'{grp}.json'
    if not jp.exists():
        print('missing', grp); continue
    j = json.loads(jp.read_text())
    names = [v['file'] for k, v in j.items() if k != '_atlas' and 'file' in v] if grp != 'lairplates' else [v['file'] for v in j['seq'].values()]
    if '_atlas' in j:
        names += j['_atlas']['sheets']
    for fn in names:
        shutil.copy(SRC / fn, W / sub / fn)
        manifest['files'][f'{sub}/{fn}'] = size(W / sub / fn)
    shutil.copy(jp, W / sub / f'{grp}.json')
    manifest[grp] = f'{sub}/{grp}.json'
(W / 'manifest.json').write_text(json.dumps(manifest, indent=1))
big = max(manifest['files'].items(), key=lambda kv: kv[1]) if manifest['files'] else None
print('ready-not-drawn files', len(manifest['files']), 'MB', round(sum(manifest['files'].values()) / 1e6, 1), 'largest', big)
