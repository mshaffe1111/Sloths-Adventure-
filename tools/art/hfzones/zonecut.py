"""Cut World 9's lava vents and eruptions and World 10's lightning rods (HF shopping list row 11, 2026-10-30) from hfzones1's pick and
pack them into the boss effects atlas, which every stage already loads (src/assets/bosses/boss-fx.webp + src/game/bossFxData.ts):
ventCool, ventHot, lava0..lava2, rodDark, rodLit, scorch. The pieces already there are lifted out as they are.
    python3 -I tools/art/hfzones/zonecut.py <takes dir> <game checkout>
"""
import json, re, sys
from pathlib import Path
from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'hfbosses'))
TAKES, GAME = Path(sys.argv[1]), Path(sys.argv[2])
sys.argv = [sys.argv[0], str(TAKES), str(GAME)]
import bosscut_lib  # noqa: E402
bosscut_lib.QA = GAME / 'reference/prop-sheets/qa-notes/hf-zones'
bosscut_lib.QA.mkdir(parents=True, exist_ok=True)
from bosscut_lib import cut, review  # noqa: E402

PICK = 'zones-s72-23'
NEW = [  # (name, box in the start's layout, options, the widest it is kept)
    ('ventCool', (20, 120, 460, 330), {'crumbs': 300}, 300),
    ('ventHot', (500, 80, 940, 330), {'crumbs': 300}, 300),
    ('lava0', (975, 20, 1262, 1015), {'mainOnly': True}, 180),
    ('lava1', (1262, 80, 1542, 1015), {'mainOnly': True}, 180),
    ('lava2', (1542, 140, 1830, 1015), {'mainOnly': True}, 180),
    ('rodDark', (90, 540, 240, 1000), {'mainOnly': True}, 70),
    ('rodLit', (300, 520, 540, 1000), {'mainOnly': True}, 110),
    ('scorch', (560, 860, 1000, 1015), {'mainOnly': True}, 240),
]
im = Image.open(TAKES / f'{PICK}.webp').convert('RGB')
new = []
scale = {}
for name, box, opts, mw in NEW:
    p = cut(im, 'magenta', box, **opts)
    # (the lit rod takes the dark rod's scale, so the two stand the same height and the rod does not jump when it lights)
    k = scale['rodDark'] if name == 'rodLit' else min(1.0, mw / p.width)
    scale[name] = k
    if k < 1:
        p = p.resize((max(1, round(p.width * k)), max(1, round(p.height * k))), Image.LANCZOS)
    new.append((name, p))
    print(name, p.size)
data = (GAME / 'src/game/bossFxData.ts').read_text()
frames0 = json.loads(re.search(r'BOSS_FX: Record<string, FxFrame> = (\{.*\});', data).group(1))
atlas0 = Image.open(GAME / 'src/assets/bosses/boss-fx.webp').convert('RGBA')
names = {n for n, _ in new}
packed = [(n, atlas0.crop((f['x'], f['y'], f['x'] + f['w'], f['y'] + f['h']))) for n, f in frames0.items() if n not in names] + new
W = 2048
x = y = rowh = 0
frames = {}
for name, p in sorted(packed, key=lambda t: -t[1].height):
    if x + p.width > W:
        x, y, rowh = 0, y + rowh + 4, 0
    frames[name] = {'x': x, 'y': y, 'w': p.width, 'h': p.height}
    x += p.width + 4
    rowh = max(rowh, p.height)
H = y + rowh
atlas = Image.new('RGBA', (W, H), (0, 0, 0, 0))
for name, p in packed:
    atlas.paste(p, (frames[name]['x'], frames[name]['y']))
atlas.save(GAME / 'src/assets/bosses/boss-fx.webp', 'WEBP', quality=88, method=6)
(GAME / 'src/assets/bosses/boss-fx.json').write_text(json.dumps(frames, indent=0))
(GAME / 'src/game/bossFxData.ts').write_text(
    '// generated by tools/art/hfbosses/bosscut.py, bosscut4.py and tools/art/hfzones/zonecut.py (2026-10-29/30): where each painted boss\n'
    '// effect, lair prop and World 9/10 hazard piece sits in src/assets/bosses/boss-fx.webp (Hugging Face img2img takes with the style\n'
    '// model; the picks and boxes are in the scripts)\n'
    'export interface FxFrame { x: number; y: number; w: number; h: number }\n'
    f'export const BOSS_FX_SIZE = {{ w: {W}, h: {H} }};\n'
    'export const BOSS_FX: Record<string, FxFrame> = ' + json.dumps(frames, separators=(',', ':')) + ';\n')
print('atlas', atlas.size, (GAME / 'src/assets/bosses/boss-fx.webp').stat().st_size)
review('zones', new)
