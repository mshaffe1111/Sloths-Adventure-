"""Pack a creature's chosen Wan clips into src/assets/enemies/<c>-anim.webp + src/game/<c>AnimData.ts.

Every frame is sized UP times the creature's old painted frames, and its anchor is the old start frame's anchor carried through the
start picture (meta.json: start px = old px * f + (ox, oy)) and the clip job's padding and scaling, so a clip frame drawn at the
old K / UP sits exactly where the old frame did.
  python3 -I pack.py <creature> '<json of {seq: [clip, [frames]] }>'
"""
import json, os, sys
from pathlib import Path
import numpy as np
from PIL import Image
H = Path(__file__).resolve().parent
S = H.parent
sys.path.insert(0, str(S / 'train'))
from clips import key as key_default  # noqa: E402
from scipy import ndimage  # noqa: E402


def key_tight(rgb):
    """for grey-skinned creatures (the snapper, the guard): only grey that reaches the edge, or a shut-in pocket of almost exactly
    the background grey, is background, so their pale grey skin stays"""
    a = rgb.astype(np.int16)
    border = np.concatenate([a[:4].reshape(-1, 3), a[-4:].reshape(-1, 3), a[:, :4].reshape(-1, 3), a[:, -4:].reshape(-1, 3)])
    bg = np.median(border, axis=0)
    d = np.abs(a - bg).max(axis=2)
    greyish = d < 22
    lab, _ = ndimage.label(greyish)
    edge = np.unique(np.concatenate([lab[0], lab[-1], lab[:, 0], lab[:, -1]]))
    fig = ~np.isin(lab, edge[edge > 0])
    lab2, n = ndimage.label(fig)
    if n > 1:
        sizes = ndimage.sum(fig, lab2, range(1, n + 1))
        fig = np.isin(lab2, 1 + np.flatnonzero(sizes > max(400, sizes.max() * 0.02)))
    lab3, n3 = ndimage.label((d < 7) & fig)
    if n3:
        sizes = ndimage.sum(np.ones_like(d), lab3, range(1, n3 + 1))
        fig &= ~np.isin(lab3, 1 + np.flatnonzero(sizes > 60))
    inner = ndimage.binary_erosion(fig, iterations=1)
    return np.where(inner, 255, np.where(fig, np.clip((d - 8) * 9, 0, 255), 0)).astype(np.uint8)


key = key_tight if os.environ.get('KEY') == 'tight' else key_default
GAME = __import__('pathlib').Path(str(__import__('pathlib').Path(__file__).resolve().parents[3]))
import os
UP = float(os.environ.get('UP', '1.5'))
c = sys.argv[1]
SEQ = json.loads(sys.argv[2])
meta = json.loads((H / 'meta.json').read_text())
CLIPDIR = S / 'gen/clips'


def bbox(a):
    ys, xs = np.nonzero(a > 128)
    return xs.min(), ys.min(), xs.max() + 1, ys.max() + 1


def start_of(clip):
    # ra-<creature>-<frame>-s<seed>  or a meta key given directly
    base = clip[3:].rsplit('-s', 1)[0]
    return base


frames, seqs = {}, {}
for seq, (clip, idxs) in SEQ.items():
    m = meta[start_of(clip)]
    fs = sorted((CLIPDIR / clip).glob(f'{clip}_*.png'))
    W, Hh = Image.open(fs[0]).size
    # the clip job padded the 1024 square start picture to the clip's shape, then scaled it
    tw, th = max(1024, round(1024 * W / Hh)), max(1024, round(1024 * Hh / W))
    px, py = (tw - 1024) // 2, (th - 1024) // 2
    sc = W / tw
    axc = (m['ax'] * m['f'] + m['ox'] + px) * sc
    ayc = (m['ay'] * m['f'] + m['oy'] + py) * sc
    F = UP / (m['f'] * sc)  # atlas px per clip px
    ims = []
    for i in idxs:
        rgb = np.asarray(Image.open(fs[i]).convert('RGB'))
        ims.append((i, np.dstack([rgb, key(rgb)])))
    U = [bbox(im[..., 3]) for _, im in ims]
    x0, y0 = min(u[0] for u in U), min(u[1] for u in U)
    x1, y1 = max(u[2] for u in U), max(u[3] for u in U)
    names = []
    for i, im in ims:
        n = f'{seq}_{i:02d}'
        cimg = Image.fromarray(im[y0:y1, x0:x1].astype(np.uint8), 'RGBA')
        cimg = cimg.resize((max(1, round(cimg.width * F)), max(1, round(cimg.height * F))), Image.LANCZOS)
        tb = cimg.getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox()
        cimg = cimg.crop(tb)
        frames[n] = (cimg, (axc - x0) * F - tb[0], (ayc - y0) * F - tb[1])
        names.append(n)
    seqs[seq] = names
    print(seq, clip, len(idxs), 'frames', frames[names[0]][0].size)

Wd, pad = 2048, 2
order = sorted(frames, key=lambda n: -frames[n][0].height)
x = y = rowh = 0
pos = {}
for n in order:
    im = frames[n][0]
    if x + im.width + pad > Wd:
        x = 0; y += rowh + pad; rowh = 0
    pos[n] = (x, y); x += im.width + pad; rowh = max(rowh, im.height)
Ht = y + rowh
atlas = Image.new('RGBA', (Wd, Ht), (0, 0, 0, 0))
for n, (px_, py_) in pos.items():
    atlas.paste(frames[n][0], (px_, py_))
out = GAME / f'src/assets/enemies/{c}-anim.webp'
atlas.save(out, 'WEBP', quality=80, method=6)
data = {n: {'x': pos[n][0], 'y': pos[n][1], 'w': frames[n][0].width, 'h': frames[n][0].height,
            'ax': round(frames[n][1], 1), 'ay': round(frames[n][2], 1)} for n in sorted(frames)}
Cap = c.upper()
ts = (f'/** Generated by scratchpad/reanim/pack.py from Wan 2.2 clips (motion model) of the {c}\'s own painted poses. Frames face RIGHT;\n'
      f' * ax/ay carry the old frames\' anchor, sized ANIM_UP times the old frames (draw at the old K / ANIM_UP). */\n')
ts += "import type { AnimFrame } from './creatureAnim.ts';\n"
ts += f'export const {Cap}_ANIM_UP = {UP};\n'
ts += f'export const {Cap}_ANIM_URL = new URL(\'../assets/enemies/{c}-anim.webp\', import.meta.url).href;\n'
ts += f'export const {Cap}_SEQ: Record<string, readonly string[]> = ' + json.dumps(seqs) + ';\n'
ts += f'export const {Cap}_ANIM: Record<string, AnimFrame> = ' + json.dumps(data) + ';\n'
(GAME / f'src/game/{c}AnimData.ts').write_text(ts)
print('atlas', Wd, Ht, len(frames), 'frames', round(out.stat().st_size / 1024), 'KB')
