"""Add the new Venom Fang figures (set 1) to the in-game atlas, next to the old frames.
usage: python3 pack_venom_new.py <cutdir from cut_boss.py> <old atlas.webp> <old venomAtlasData.ts> <out atlas.webp> <out venomAtlasData.ts>
The old frames keep their names and places; the new ones are added under them as n_<name> at SCALE, anchored on the middle of the
body mass on the ground line (found as the lowest row that is at least 35% as wide as the figure)."""
import json, re, sys
import numpy as np
from PIL import Image

SCALE = 0.58
NEW = {  # name: cut figure
    'n_idle': 's1_01', 'n_rear': 's6_01', 'n_roar': 's5_10', 'n_hiss': 's5_11', 'n_strike': 's5_02', 'n_bite': 's5_06',
    'n_lunge': 's3_02', 'n_lunge2': 's4_14', 'n_tail': 's4_10', 'n_tail2': 's5_08', 'n_tail3': 's5_09', 'n_coil': 's7_00',
    'n_ring': 's7_05', 'n_ball': 's6_09', 'n_flat': 's7_02', 'n_low': 's7_01', 'n_glide': 's6_14', 'n_wave': 's4_06', 'n_wave2': 's4_05',
}

def anchor(im):
    a = np.asarray(im)[..., 3] > 100
    cols = a.sum(0); rows = a.sum(1)
    wide = np.where(rows >= 0.35 * (cols > 0).sum())[0]
    gy = int(wide.max()) if len(wide) else im.height - 1
    ys, xs = np.where(a[max(0, gy - im.height // 3):gy + 1])
    return float(xs.mean()), float(gy + 1)

def main(cutdir, old_atlas, old_data, out_atlas, out_data):
    src = open(old_data).read()
    frames = json.loads(re.search(r'FRAMES: Record<string, BossFrame> = (\{.*\});', src).group(1))
    old = Image.open(old_atlas).convert('RGBA')
    W, oh = old.size
    figs = []
    for n, f in NEW.items():
        im = Image.open(f'{cutdir}/{f}.png')
        im = im.resize((max(1, round(im.width * SCALE)), max(1, round(im.height * SCALE))), Image.LANCZOS)
        ax, ay = anchor(im); figs.append((n, im, ax, ay))
    x = 0; y = oh + 2; rh = 0; pos = {}
    for n, im, ax, ay in figs:
        if x + im.width > W: x = 0; y += rh + 2; rh = 0
        pos[n] = (x, y); x += im.width + 2; rh = max(rh, im.height)
    H = y + rh
    atlas = Image.new('RGBA', (W, H), (0, 0, 0, 0)); atlas.paste(old, (0, 0))
    for n, im, ax, ay in figs:
        atlas.paste(im, pos[n]); frames[n] = dict(x=pos[n][0], y=pos[n][1], w=im.width, h=im.height, ax=round(ax, 1), ay=round(ay, 1))
    atlas.save(out_atlas, quality=90, method=6)
    open(out_data, 'w').write(f"""/** Generated by pack_boss.py (frames from the first Gemini Venom Fang sheets) plus pack_venom_new.py (n_* frames, from set 1 of the redrawn sheets). Frames face RIGHT; ax/ay is the middle of the body on the ground line. */
export interface BossFrame {{ x: number; y: number; w: number; h: number; ax: number; ay: number }}
export const VENOM_ATLAS_SIZE = {{ w: {W}, h: {H} }};
export const VENOM_FRAMES: Record<string, BossFrame> = {json.dumps(frames)};
""")
    print(len(frames), 'frames', W, H)

if __name__ == '__main__': main(*sys.argv[1:])
